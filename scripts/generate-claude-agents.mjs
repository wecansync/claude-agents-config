#!/usr/bin/env node
// claude-agents-config:managed

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const homeArgIndex = process.argv.indexOf("--home");
const home = homeArgIndex >= 0 && process.argv[homeArgIndex + 1]
  ? resolve(process.argv[homeArgIndex + 1])
  : process.env.CLAUDE_FLEET_HOME
    ? resolve(process.env.CLAUDE_FLEET_HOME)
    : homedir();
const fleetPath = join(home, ".config", "delegate-skills", "config.json");
const settingsPath = join(home, ".claude", "settings.json");
const agentsDir = join(home, ".claude", "agents");
const marker = "GENERATED BY claude-fleet-sync";
const checkOnly = process.argv.includes("--check");
const quiet = process.argv.includes("--quiet");

function fail(message) {
  process.stderr.write(`claude-fleet-sync: ${message}\n`);
  process.exit(1);
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    fail(`cannot read ${path}: ${error.message}`);
  }
}

function yamlString(value) {
  return JSON.stringify(String(value));
}

function laneRole(lane, config) {
  if (lane === "plan" || lane === "plan-alt") return "plan";
  if (lane === "review" || lane.startsWith("review-")) return "review";
  if (lane === "diagnose-static") return "diagnose";
  if (lane === "security-review") return "security";
  if (lane === "research-codebase") return "research";
  if (lane === "research-web") return "research-web";
  if (lane === "explore-narrow") return "explore";
  if (lane === "triage-static") return "triage";
  if (lane === "ui") return "ui";
  if (lane === "tests") return "tests";
  if (lane === "docs") return "docs";
  if (lane === "implement" || lane.startsWith("implement-")) return "implement";
  return config.readOnly ? "review" : "implement";
}

const memoryTools = "mcp__agent-brain-memory__memory_search, mcp__agent-brain-memory__memory_save, mcp__agent-brain-memory__session_summary";
