const FLEET_FALLBACK_DESCRIPTION = "Required by delegate fleet";

function descriptionFor(lane, model, role, config) {
  const spec = roleConfig[role];
  if (config.description) return `${config.description} Runs on ${model}.`;
  if (autoLanes.has(lane)) {
    return `${spec.trigger} Runs on ${model}.`;
  }
  return `Alternate ${role} lane on ${model}. Use when the user names this lane or model, or when the primary ${role} lane must be avoided for quota, independence, or repeated failure.`;
}

function renderAgent(lane, config, sourceHash, picker) {
  const role = laneRole(lane, config);
  const spec = roleConfig[role];
  if (!spec) fail(`no agent role mapping for lane ${lane}`);
  const agentName = `fleet-${lane}`;
  const fallbacks = candidatesFor(config).slice(1, 4).filter((model) => !picker || picker.has(model));
  const fallbackLine = fallbacks.length ? `fallbackModel: ${yamlString(fallbacks.join(","))}\n` : "";
  return `---\nname: ${agentName}\ndescription: ${yamlString(descriptionFor(lane, config.model, role, config))}\nmodel: ${yamlString(config.model)}\n${fallbackLine}effort: ${config.effort || "high"}\ntools: ${spec.tools}\nbackground: true\nomitClaudeMd: true\ncolor: ${spec.color}\nmaxTurns: ${spec.maxTurns}\n---\n\n<!-- ${marker}; source-sha256: ${sourceHash} -->\n\n# Fleet lane: ${lane}\n\nYou are the native Claude Code subagent for global fleet lane \`${lane}\`. The main agent owns decomposition, integration, final gates, and outward-facing actions. You own only the bounded assignment in your invocation.\n\n${spec.prompt}\n\nThe main agent must put every applicable project instruction, gate, and handoff requirement in the brief because this generated agent omits CLAUDE.md to keep context bounded and avoid delegated handoff writes. Project memory search may be unavailable in custom-agent sessions; use it when permitted and continue from the brief and repository evidence when it is not. Before stopping, save only durable project knowledge and write the local session summary required by the agent-brain lifecycle. If the brief lacks a decision required to continue safely, stop and report the gap instead of expanding scope.\n`;
}

function candidatesFor(config) {
  const candidates = [config.model, ...(Array.isArray(config.fallbacks) ? config.fallbacks : [])];
  return [...new Set(candidates.filter((model) => typeof model === "string" && model))];
}

function resolveModel(lane, config, picker) {
  const candidates = candidatesFor(config);
  const available = (model) => {
    const row = picker.get(model);
    return row && row.description !== FLEET_FALLBACK_DESCRIPTION;
  };
  const resolved = candidates.find(available) || candidates.find((model) => picker.has(model));
  if (!resolved) fail(`${lane} has no usable model candidate: ${candidates.join(", ") || "<missing>"}`);
  if (resolved !== config.model) {
    process.stderr.write(`claude-fleet-sync: ${lane} resolved ${config.model} -> ${resolved}\n`);
  }
  return resolved;
}

writerLockFd = lockHeld ? undefined : acquireWriterLock();
// Recover any transaction left by an interrupted prior run before this run
// reads the fleet config or settings as fresh input, so a partially-applied
// generation is never built upon.
recoverSyncTransaction();
const fleetRaw = readFileSync(fleetPath, "utf8");
const fleet = readJson(fleetPath);
const settings = readJson(settingsPath);
if (fleet.version !== "delegate-fleet.v1" || !fleet.lanes || typeof fleet.lanes !== "object") {
  fail(`${fleetPath} is not a delegate-fleet.v1 map`);
}
const picker = new Map((settings.modelPicker?.options || []).map((row) => [row.model, row]));
if (picker.size === 0) fail(`${settingsPath} has no modelPicker options`);

const laneNamePattern = /^[a-z0-9][a-z0-9-]*$/;
const resolvedModels = new Map();
for (const [lane, config] of Object.entries(fleet.lanes)) {
  if (!laneNamePattern.test(lane)) fail(`invalid lane name: ${lane}`);
  if (config.implementer !== "claude") fail(`${lane} uses unsupported implementer ${config.implementer}`);
  resolvedModels.set(lane, resolveModel(lane, config, picker));
}

const sourceHash = createHash("sha256").update(fleetRaw).digest("hex").slice(0, 16);
const fleetHash = createHash("sha256").update(fleetRaw).digest("hex");
const desired = new Map();
for (const [lane, config] of Object.entries(fleet.lanes)) {
  desired.set(`fleet-${lane}.md`, renderAgent(lane, { ...config, model: resolvedModels.get(lane) }, sourceHash, picker));
}

if (!checkOnly) mkdirSync(agentsDir, { recursive: true });
const existing = new Map();
for (const filename of [...desired.keys()]) {
  const path = join(agentsDir, filename);
  if (existsSync(path)) existing.set(filename, readFileSync(path, "utf8"));
}

const stale = [];
// Discover stale generated fleet files without touching hand-authored agents.
for (const filename of readdirSync(agentsDir)) {
  if (!filename.startsWith("fleet-") || !filename.endsWith(".md") || desired.has(filename)) continue;
  const path = join(agentsDir, filename);
  const content = readFileSync(path, "utf8");
  if (content.includes(marker)) stale.push(filename);
}

const changed = [];
const blocked = [];
for (const [filename, content] of desired) {
  const path = join(agentsDir, filename);
  if (!existsSync(path)) {
    changed.push(filename);
    continue;
  }
  const current = readFileSync(path, "utf8");
  if (!current.includes(marker)) blocked.push(filename);
  else if (current !== content) changed.push(filename);
}
if (blocked.length) fail(`refusing to overwrite hand-authored agent(s): ${blocked.join(", ")}`);

if (checkOnly) {
  // --check must never mutate a target and must never leak the writer lock:
  // a leaked lock file would otherwise sit until the 60-second staleness
  // window elapses, deferring the next real writer for no reason.
  releaseWriterLock(writerLockFd);
  writerLockFd = undefined;
  if (changed.length || stale.length) {
    process.stderr.write(`claude-fleet-sync: drift detected: ${changed.length} changed/missing, ${stale.length} stale\n`);
    if (changed.length) process.stderr.write(`  changed/missing: ${changed.join(", ")}\n`);
    if (stale.length) process.stderr.write(`  stale: ${stale.join(", ")}\n`);
    process.exit(1);
  }
  if (!quiet) process.stdout.write(`claude-fleet-sync: ${desired.size} agents are in sync (${sourceHash})\n`);
  process.exit(0);
}

try {
  const verification = buildInstalledVerification(desired, fleetHash);
  commitGeneratedFiles(desired, verification, stale);
} finally {
  releaseWriterLock(writerLockFd);
}

if (!quiet) {
  process.stdout.write(`claude-fleet-sync: synced ${desired.size} agents (${changed.length} changed/missing, ${stale.length} removed, ${sourceHash})\n`);
}
