function realpathOrResolve(path) {
  // Resolve symlinks canonically, including through ancestors that don't
  // themselves exist yet (e.g. a target file about to be created inside an
  // existing, possibly symlinked, directory tree such as macOS's
  // /var -> /private/var). Falling back to a plain normalize() for the
  // whole path when the leaf is missing would silently stop canonicalizing
  // the existing ancestors too, which is exactly what containment checks
  // must not do.
  const absolute = resolve(path);
  try {
    return realpathSync.native(absolute);
  } catch {
    const parent = resolve(absolute, "..");
    if (parent === absolute) return absolute;
    return join(realpathOrResolve(parent), absolute.slice(parent.length + 1));
  }
}

