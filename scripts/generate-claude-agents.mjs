let writerLockFd;

function fail(message) {
  releaseWriterLock(writerLockFd);
  writerLockFd = undefined;
  process.stderr.write(`claude-fleet-sync: ${message}\n`);
  process.exit(1);
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    fail(`cannot read ${path}: ${error.message}`);
  }
}

function yamlString(value) {
  return JSON.stringify(String(value));
}

function failIfSymlink(path, label) {
  try {
    if (lstatSync(path).isSymbolicLink()) fail(`refusing to write through symlinked ${label}: ${path}`);
  } catch (error) {
    if (error?.code !== "ENOENT") fail(`cannot inspect ${label} ${path}: ${error.message}`);
  }
}

function failIfSymlinkChain(path, label) {
  let current = resolve(path);
  const missing = [];
  while (true) {
    try {
      if (lstatSync(current).isSymbolicLink()) fail(`refusing to write through symlinked ${label}: ${current}`);
      break;
    } catch (error) {
      if (error?.code !== "ENOENT") fail(`cannot inspect ${label} ${current}: ${error.message}`);
      missing.push(current);
      const parent = resolve(current, "..");
      if (parent === current) break;
      current = parent;
    }
  }
}

function acquireWriterLock() {
  failIfSymlinkChain(home, "home parent");
  failIfSymlink(home, "home");
  failIfSymlink(agentsDir, "agents directory");
  failIfSymlink(installMetadataPath, "install metadata");
  failIfSymlink(installManifestPath, "install manifest");
  // This lock path is derived identically here, in sync-omniroute-models.mjs,
  // and in provider_catalog.lock_path (Python), so all three writers share
  // one canonical file per resolved home. A lock older than 60 seconds is
  // treated as an orphan from a crashed writer and reclaimed; a lock younger
  // than that is a live owner and must never be evicted.
  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      const fd = openSync(writerLockPath, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL, 0o600);
      writeFileSync(fd, String(process.pid), "utf8");
      return fd;
    } catch (error) {
      if (error?.code !== "EEXIST") fail(`cannot acquire fleet writer lock: ${error.message}`);
      if (attempt > 0) break;
      try {
        if (Date.now() - statSync(writerLockPath).mtimeMs < 60_000) break;
        unlinkSync(writerLockPath);
        continue;
      } catch {
        break;
      }
    }
  }
  fail(`another fleet writer holds ${writerLockPath}`);
}

function releaseWriterLock(fd) {
  if (fd === undefined) return;
  try { closeSync(fd); } catch {}
  try { unlinkSync(writerLockPath); } catch {}
}

function writeAgentAtomically(path, content, mode = 0o644) {
  failIfSymlinkChain(path, "agent parent");
  failIfSymlink(path, "agent file");
  const temp = `${path}.tmp.${process.pid}.${createHash("sha256").update(String(Date.now()) + Math.random()).digest("hex").slice(0, 12)}`;
  try {
    const fd = openSync(temp, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL, mode);
    try {
      writeFileSync(fd, content, "utf8");
      fsyncSync(fd);
    } finally {
      closeSync(fd);
    }
    chmodSync(temp, mode);
    renameSync(temp, path);
  } catch (error) {
    try { unlinkSync(temp); } catch {}
    fail(`cannot write generated agent ${path}: ${error.message}`);
  }
}

function readJsonOptional(file) {
  if (!existsSync(file)) return null;
  return readJson(file);
}

function writeTransactionJson(file, value, mode = 0o600) {
  writeAgentAtomically(file, Buffer.from(JSON.stringify(value, null, 2) + "\n", "utf8"), mode);
}

function withinManagedSyncPaths(targetPath) {
  const resolved = realpathOrResolve(targetPath);
  if (resolved === realpathOrResolve(installManifestPath) || resolved === realpathOrResolve(installMetadataPath)) return true;
  const rel = relative(realpathOrResolve(agentsDir), resolved);
  return Boolean(rel) && !rel.startsWith("..") && !rel.includes("/") && !rel.includes("\\");
}

function recoverSyncTransaction() {
  // Consume any transaction left by an interrupted prior run before this run
  // treats the fleet config or settings as fresh input. A validated
  // "prepared" transaction is rolled back to its recorded prior state; a
  // validated "committed" transaction only needs its bookkeeping evidence
  // removed, since its target writes already succeeded. Any manifest or
  // marker that fails validation is left untouched on disk (via `fail`,
  // which never deletes evidence) so an operator can inspect it.
  const marker = readJsonOptional(syncTransactionMarker);
  if (marker === null) {
    if (existsSync(syncTransactionMarker)) fail(`malformed sync transaction marker preserved at ${syncTransactionMarker}`);
    return;
  }
  if (!marker || typeof marker !== "object" || marker.format !== "claude-agents-config.sync-transaction.v1" || typeof marker.directory !== "string") {
    fail(`malformed sync transaction marker preserved at ${syncTransactionMarker}`);
  }
  const directory = resolve(marker.directory);
  if (!existsSync(directory)) {
    fail(`sync transaction marker points at a missing directory: ${directory}`);
  }
  // Compare canonical (symlink-resolved) paths, not merely normalized ones:
  // on platforms where the home (or its ancestors, e.g. macOS's
  // /var -> /private/var) is itself a symlink, a literal string comparison
  // of un-resolved paths would reject a genuinely contained transaction
  // directory. Resolving both sides to their real paths before comparing
  // keeps the containment check meaningful without weakening it.
  if (realpathOrResolve(directory) !== realpathOrResolve(resolve(syncTransactionDir))) {
    fail(`sync transaction directory is outside the installed home; evidence preserved at ${marker.directory}`);
  }
  const manifestPath = join(directory, "manifest.json");
  const manifest = readJsonOptional(manifestPath);
  if (!manifest || typeof manifest !== "object" || manifest.format !== "claude-agents-config.sync-transaction.v1" || !Array.isArray(manifest.records) || manifest.records.length === 0) {
    fail(`sync transaction manifest is invalid; evidence preserved at ${directory}`);
  }
  const seenTargets = new Set();
  for (const [index, record] of manifest.records.entries()) {
    if (!record || typeof record !== "object" || typeof record.path !== "string" || !withinManagedSyncPaths(record.path)) {
      fail(`sync transaction record ${index} is invalid; evidence preserved at ${directory}`);
    }
    const resolvedTarget = resolve(record.path);
    if (seenTargets.has(resolvedTarget)) fail(`sync transaction target repeats: ${record.path}; evidence preserved at ${directory}`);
    seenTargets.add(resolvedTarget);
    if (typeof record.existed !== "boolean") fail(`sync transaction record ${index} has an invalid existed flag; evidence preserved at ${directory}`);
    if (record.existed) {
      if (
        typeof record.previous !== "string" ||
        !/^[A-Za-z0-9+/]*={0,2}$/.test(record.previous) ||
        typeof record.mode !== "number" ||
        (record.mode & ~0o777) !== 0
      ) {
        fail(`sync transaction record ${index} has an invalid backup; evidence preserved at ${directory}`);
      }
    }
  }
  const committed = manifest.state === "committed" || marker.state === "committed";
  if (!committed) {
    for (const record of manifest.records) {
      if (record.existed) writeAgentAtomically(record.path, Buffer.from(record.previous, "base64"), record.mode);
      else if (existsSync(record.path)) rmSync(record.path);
    }
  }
  for (const child of readdirSync(directory)) unlinkSync(join(directory, child));
  rmSync(directory, { recursive: true });
  unlinkSync(syncTransactionMarker);
}

function commitGeneratedFiles(desired, verification, stale) {
  const files = [];
  for (const [filename, content] of desired) files.push({ path: join(agentsDir, filename), content: Buffer.from(content, "utf8"), mode: 0o644 });
  for (const filename of stale) files.push({ path: join(agentsDir, filename), content: null, mode: null });
  for (const [path, content] of verification) files.push({ path, content, mode: 0o600 });
  failIfSymlinkChain(syncTransactionDir, "sync transaction parent");
  mkdirSync(syncTransactionDir, { recursive: true, mode: 0o700 });
  const records = [];
  for (const [index, item] of files.entries()) {
    failIfSymlink(item.path, "transaction target");
    const payload = join(syncTransactionDir, `${String(index).padStart(4, "0")}.bin`);
    const existed = existsSync(item.path);
    const previous = existed ? readFileSync(item.path) : null;
    if (item.content !== null) writeAgentAtomically(payload, item.content, 0o600);
    records.push({ path: item.path, existed, previous: previous ? previous.toString("base64") : null, payload: item.content !== null ? payload : null, mode: existed ? (lstatSync(item.path).mode & 0o777) : item.mode });
  }
  writeTransactionJson(join(syncTransactionDir, "manifest.json"), { format: "claude-agents-config.sync-transaction.v1", state: "prepared", records });
  writeTransactionJson(syncTransactionMarker, { format: "claude-agents-config.sync-transaction.v1", state: "prepared", directory: syncTransactionDir });
  try {
    for (const item of files) {
      failIfSymlink(item.path, "transaction target");
      if (item.content === null) { if (existsSync(item.path)) rmSync(item.path); }
      else writeAgentAtomically(item.path, item.content, item.mode);
    }
    const manifest = { format: "claude-agents-config.sync-transaction.v1", state: "committed", records };
    writeTransactionJson(join(syncTransactionDir, "manifest.json"), manifest);
    writeTransactionJson(syncTransactionMarker, { format: manifest.format, state: "committed", directory: syncTransactionDir });
    for (const child of readdirSync(syncTransactionDir)) unlinkSync(join(syncTransactionDir, child));
    rmSync(syncTransactionDir, { recursive: true });
    unlinkSync(syncTransactionMarker);
  } catch (error) {
    try {
      for (const record of records) {
        if (record.existed) writeAgentAtomically(record.path, Buffer.from(record.previous, "base64"), record.mode);
        else if (existsSync(record.path)) rmSync(record.path);
      }
    } catch (rollbackError) {
      fail(`fleet sync failed (${error.message}) and rollback failed (${rollbackError.message}); transaction evidence retained at ${syncTransactionDir}`);
    }
    throw error;
  }
}

function buildInstalledVerification(desiredByFilename, fleetHash) {
  const manifest = readJsonOptional(installManifestPath);
  const metadata = readJsonOptional(installMetadataPath);
  if (!manifest && !metadata) return new Map();
  if (!manifest || !metadata || !Array.isArray(manifest.managed) || !Array.isArray(metadata.managed)) {
    fail("installed verification metadata is incomplete; refusing to change generated agents");
  }
  const byPath = new Map(desiredByFilename);
  const updateRecords = (records) => records.map((record) => {
    if (!record || typeof record.path !== "string") return record;
    const filename = relative(agentsDir, record.path);
    if (filename && !filename.startsWith("..") && !filename.includes("/") && !filename.includes("\\")) {
      const content = byPath.get(filename);
      if (content !== undefined) {
        return { ...record, sha256: createHash("sha256").update(content).digest("hex") };
      }
    }
    return record;
  });
  const nextManifest = {
    ...manifest,
    managed: updateRecords(manifest.managed),
    fleetSha256: fleetHash,
  };
  const nextManifestBytes = Buffer.from(JSON.stringify(nextManifest, null, 2) + "\n", "utf8");
  const nextMetadata = {
    ...metadata,
    managed: updateRecords(metadata.managed),
    verificationSha256: createHash("sha256").update(nextManifestBytes).digest("hex"),
  };
  return new Map([
    [installManifestPath, nextManifestBytes],
    [installMetadataPath, Buffer.from(JSON.stringify(nextMetadata, null, 2) + "\n", "utf8")],
  ]);
}

function laneRole(lane, config) {
  if (lane === "plan" || lane === "plan-alt") return "plan";
  if (lane === "review" || lane.startsWith("review-")) return "review";
  if (lane === "diagnose-static") return "diagnose";
  if (lane === "security-review") return "security";
  if (lane === "research-codebase") return "research";
  if (lane === "research-web") return "research-web";
  if (lane === "explore-narrow") return "explore";
  if (lane === "triage-static") return "triage";
  if (lane === "ui") return "ui";
  if (lane === "tests") return "tests";
  if (lane === "docs") return "docs";
  if (lane === "implement" || lane.startsWith("implement-")) return "implement";
  return config.readOnly ? "review" : "implement";
}

