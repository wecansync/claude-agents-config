def env_home() -> Path:
    # Native Windows uses USERPROFILE/HOMEDRIVE+HOMEPATH as its authoritative
    # home.  A POSIX HOME may be present under Git Bash and must not silently
    # redirect a native invocation.  Unix-like systems prefer HOME, while still
    # accepting the Windows variables for portable test/sandbox invocations.
    if os.name == "nt":
        value = (
            os.environ.get("USERPROFILE")
            or (os.environ.get("HOMEDRIVE", "") + os.environ.get("HOMEPATH", ""))
            or os.environ.get("HOME")
        )
    else:
        value = (
            os.environ.get("HOME")
            or os.environ.get("USERPROFILE")
            or (os.environ.get("HOMEDRIVE", "") + os.environ.get("HOMEPATH", ""))
        )
    if value:
        return resolve_dir(value)
    try:
        return Path.home().resolve(strict=False)
    except RuntimeError:
        fail("cannot determine the user home; pass --home or --prefix")


def target_home(args: argparse.Namespace) -> Path:
    if args.home:
        return resolve_dir(args.home)
    if args.prefix:
        return resolve_dir(args.prefix)
    return env_home()


def config_home(args: argparse.Namespace, home: Path, previous: dict | None = None) -> Path:
    if args.config_home:
        path = resolve_dir(args.config_home)
        if not path.is_absolute():
            fail("--config-home must resolve to an absolute path")
        return path
    if previous and isinstance(previous.get("configHome"), str) and not (args.prefix and not args.home):
        return resolve_dir(previous["configHome"])
    # A prefix-only sandbox is self-contained and must not depend on the caller's
    # XDG setting.  Normal installs honor XDG_CONFIG_HOME on Linux/macOS.
    if args.prefix and not args.home:
        return resolve_dir(args.prefix) / ".config"
    xdg = os.environ.get("XDG_CONFIG_HOME")
    if xdg:
        path = resolve_dir(xdg)
        if path.is_absolute():
            return path
    return home / ".config"


def target_bin(args: argparse.Namespace, home: Path) -> Path:
    if args.prefix:
        return resolve_dir(args.prefix) / "bin"
    return home / ".local" / "bin"


def normalize_hooks(value: object, home: Path) -> object:
    if isinstance(value, str):
        return value.replace("__CLAUDE_HOME__", str(home / ".claude"))
    if isinstance(value, list):
        return [normalize_hooks(item, home) for item in value]
    if isinstance(value, dict):
        return {key: normalize_hooks(item, home) for key, item in value.items()}
    return value


def command_text(item: object) -> str:
    if not isinstance(item, dict):
        return ""
    hooks = item.get("hooks")
    if not isinstance(hooks, list):
        return str(item.get("command", ""))
    return " ".join(str(h.get("command", "")) for h in hooks if isinstance(h, dict))


# Maps each pre-marker legacy command fragment to the claude-agents-config
