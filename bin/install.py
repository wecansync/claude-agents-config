def posix_sync_wrapper(generator: Path, home: Path, config_root: Path) -> bytes:
    command = "exec node " + " ".join(
        shlex.quote(str(part)) for part in (generator, "--home", home, "--config-home", config_root)
    ) + " \"$@\""
    return ("#!/usr/bin/env bash\nset -euo pipefail\n" + command + "\n").encode("utf-8")


def posix_python_wrapper(script: Path, home: Path, prefix: Path, config_root: Path) -> bytes:
    parts = [
        sys.executable,
        str(script),
        "--home",
        str(home),
        "--prefix",
        str(prefix),
        "--config-home",
        str(config_root),
    ]
    command = " ".join(shlex.quote(str(part)) for part in parts)
    return ("#!/usr/bin/env bash\nset -euo pipefail\nexec " + command + " \"$@\"\n").encode("utf-8")


def cmd_dispatch(
    script: Path,
    runtime: str,
    home: Path | None = None,
    prefix: Path | None = None,
    config_root: Path | None = None,
) -> bytes:
    def quote(value: Path | str) -> str:
        # Batch treats metacharacters safely inside a quoted argument for the
        # normal path characters supported by Windows, including spaces and
        # Unicode. A target may live outside the wrapper's prefix (XDG-style).
        return '"' + str(value).replace('"', '""') + '"'

    args = ""
    if home is not None:
        args += " --home " + quote(home)
    if prefix is not None:
        args += " --prefix " + quote(prefix)
    if config_root is not None:
        args += " --config-home " + quote(config_root)
    script_arg = quote(script)
    if runtime == "node":
        body = f"@echo off\r\nsetlocal\r\nwhere node >nul 2>nul\r\nif errorlevel 1 (echo Node.js ^>=18 is required 1^>^&2 & exit /b 1)\r\nnode {script_arg}{args} %*\r\nexit /b %errorlevel%\r\n"
    else:
        # Try the interpreter this installer ran under first: on a machine
        # whose only Python is off PATH (e.g. uv-managed), bare "python" is
        # the Microsoft Store stub and "py" may not exist either, so the
        # shim would exit 9009 even though hook_command_for's hooks (pinned
        # the same way) work fine. "if not exist ... goto" is required
        # instead of a parenthesized "if errorlevel" block: %errorlevel%
        # expands at parse time, so it would read stale inside parentheses.
        pinned = quote(sys.executable)
        body = (
            f"@echo off\r\nsetlocal EnableExtensions DisableDelayedExpansion\r\n"
            f"if not exist {pinned} goto no_pin\r\n"
            f"{pinned} {script_arg}{args} %*\r\n"
            f"exit /b %errorlevel%\r\n"
            f":no_pin\r\n"
            f"where py >nul 2>nul\r\n"
            f"if not errorlevel 1 goto run_py\r\n"
            f"python {script_arg}{args} %*\r\n"
            f"exit /b %errorlevel%\r\n"
            f":run_py\r\n"
            f"py -3 {script_arg}{args} %*\r\n"
            f"exit /b %errorlevel%\r\n"
        )
    return body.encode("utf-8")


def powershell_dispatch(
    script: Path,
    runtime: str,
    home: Path | None = None,
    prefix: Path | None = None,
    config_root: Path | None = None,
) -> bytes:
    def ps_quote(value: str) -> str:
        return "'" + value.replace("'", "''") + "'"
    path = ps_quote(str(script))
    target_args = ""
    if home is not None:
        target_args += " --home " + ps_quote(str(home))
    if prefix is not None:
        target_args += " --prefix " + ps_quote(str(prefix))
    if config_root is not None:
        target_args += " --config-home " + ps_quote(str(config_root))
    if runtime == "node":
        body = f"$node = Get-Command node -ErrorAction SilentlyContinue\nif (-not $node) {{ throw 'Node.js >=18 is required' }}\n& $node.Source {path}{target_args} @args\nexit $LASTEXITCODE\n"
    else:
        # Same pinned-interpreter-first fallback as cmd_dispatch, for the
        # same reason (see its comment). ps_quote's single-quoted literals
        # keep this compatible with Windows PowerShell 5.1, which strips a
        # double quote embedded inside a native-command argument.
        pinned = ps_quote(sys.executable)
        body = (
            f"$py = Get-Command py -ErrorAction SilentlyContinue\n"
            f"if (Test-Path -LiteralPath {pinned}) {{ & {pinned} {path}{target_args} @args }} "
            f"elseif ($py) {{ & $py.Source '-3' {path}{target_args} @args }} "
            f"else {{ $python = Get-Command python -ErrorAction Stop; & $python.Source {path}{target_args} @args }}\n"
            f"exit $LASTEXITCODE\n"
        )
    return body.encode("utf-8")


def merged_policy_bytes(bundle: Path, config_root: Path) -> bytes:
    """The provider policy this install writes: the shipped policy, carrying
    the user's recorded decisions and, for an existing install, its
    provider-specific model families and aliases.

    An installed policy describes the user's own provider (its families,
    aliases, and context conventions), so an update must not replace it with
    the generic shipped defaults: explicit approvedFamilies would then name
    families the new policy does not define and approve nothing.
    """
    fleet = config_root / "delegate-skills"
    policy_data = source_bytes(bundle, PROVIDER_POLICY_PATH)
    existing_policy_path = fleet / "provider-policy.json"
    if existing_policy_path.is_file():
        try:
            source_policy = json.loads(policy_data.decode("utf-8"))
        except (UnicodeError, json.JSONDecodeError) as exc:
            fail(f"bundled provider policy is not valid JSON ({exc})")
        try:
            existing_policy = json.loads(existing_policy_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            # An installed policy that cannot be read or parsed may hold a
            # user's explicit family-approval decisions; silently falling
            # back to the shipped all-approved defaults here would resurrect
            # every revoked family. Abort before any target is touched
            # (this runs before create_backup/stage_and_commit) and leave
            # the damaged file exactly as found for the operator to inspect.
            fail(f"existing provider policy at {existing_policy_path} is unreadable or not valid JSON ({exc}); resolve or restore it before installing")
        if not isinstance(existing_policy, dict):
            fail(f"existing provider policy at {existing_policy_path} is not a JSON object; resolve or restore it before installing")
        # An explicit approvedFamilies allowlist is the authoritative record
        # of the user's decisions (see family_approved() in
        # provider_catalog.py). If it is present but malformed -- null, not
        # a list, containing a non-string element, or naming a family the
        # policy does not even define -- its meaning is ambiguous, and it
        # must never be silently discarded or defaulted to "approve
        # everything": that would be a fail-open on a security-relevant
        # allowlist. Abort instead.
        if "approvedFamilies" in existing_policy:
            approved_families = existing_policy["approvedFamilies"]
            if not isinstance(approved_families, list) or any(not isinstance(value, str) for value in approved_families):
                fail(f"existing provider policy at {existing_policy_path} has an invalid approvedFamilies list; resolve or restore it before installing")
            known_names = {
                family.get("name")
                for family in existing_policy.get("families", [])
                if isinstance(family, dict) and isinstance(family.get("name"), str)
            }
            unknown = sorted(set(approved_families) - known_names)
            if unknown:
                fail(f"existing provider policy at {existing_policy_path} approves unknown family/families {unknown}; resolve or restore it before installing")
        if isinstance(source_policy, dict):
            for key in ("approvedFamilies", "discoveryApproved", "decisionsFormat"):
                if key in existing_policy:
                    source_policy[key] = copy.deepcopy(existing_policy[key])
            provider_keys = ("provider", "families", "runtimeAliases", "namespaceAliases", "contextSuffix", "oneMContextThreshold", "modelTiers")
            if isinstance(existing_policy.get("families"), list) and existing_policy.get("families"):
                for key in provider_keys:
                    if key in existing_policy:
                        source_policy[key] = copy.deepcopy(existing_policy[key])
            # The shipped families array always ships with "approved":
            # true, so once explicit decisions exist, an update must not
            # merely preserve the top-level approvedFamilies list while
            # silently restoring the shipped per-family flag: that stale
            # flag is exactly what family_approved() falls back to before
            # any decision is recorded, and would otherwise contradict
            # (and, via any future fallback path, re-enable) a family the
            # user explicitly revoked.
            approved_families = source_policy.get("approvedFamilies")
            if isinstance(approved_families, list):
                approved_set = {value for value in approved_families if isinstance(value, str)}
                for family in source_policy.get("families", []):
                    if isinstance(family, dict) and isinstance(family.get("name"), str):
                        family["approved"] = family["name"] in approved_set
            policy_data = json_bytes(source_policy)
    return policy_data


def install_policy(policy_data: bytes) -> dict:
    try:
        value = json.loads(policy_data.decode("utf-8"))
    except (UnicodeError, json.JSONDecodeError) as exc:
        fail(f"provider policy is not valid JSON ({exc})")
    if not isinstance(value, dict):
        fail("provider policy is not a JSON object")
    return value


def saved_gateway_profiles(home: Path, url: str) -> list[dict]:
    """The agentfleet gateway profiles saved for this endpoint, most recently
    saved first. The installer only reads the profile store; agentfleet owns it.
    """
    store = home / ".claude" / "agentfleet" / "profiles"
    if not store.is_dir() or store.is_symlink():
        return []
    found = []
    for path in sorted(store.glob("*.json")):
        if path.is_symlink() or not path.is_file():
            continue
        try:
            profile = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            continue
        if not isinstance(profile, dict) or profile.get("kind") != "gateway":
            continue
        env = profile.get("env") if isinstance(profile.get("env"), dict) else {}
        if same_endpoint(env.get("ANTHROPIC_BASE_URL"), url):
            found.append({**profile, "name": path.stem})
    # Stable sort: newest savedAt first, name order among equals.
    found.sort(key=lambda profile: str(profile.get("savedAt") or ""), reverse=True)
    return found


def rebased_fleet(live: dict, profile: dict | None) -> dict:
    """The installed fleet with another provider's choices: the saved
    profile's lane pins, tier labels, and exclusions, or none at all.

    Custom lanes stay; lanes left without a model are resolved against the
    new provider's catalog.
    """
    result = copy.deepcopy(live) if isinstance(live.get("lanes"), dict) else {"lanes": {}}
    saved_lanes = (profile or {}).get("lanes")
    saved_lanes = saved_lanes if isinstance(saved_lanes, dict) else {}
    for name, config in result["lanes"].items():
        if not isinstance(config, dict):
            continue
        for field in CARRIED_LANE_FIELDS:
            config.pop(field, None)
        saved = saved_lanes.get(name)
        if isinstance(saved, dict):
            config.update({field: copy.deepcopy(saved[field]) for field in CARRIED_LANE_FIELDS if field in saved})
    tiers = (profile or {}).get("modelTiers")
    result["modelTiers"] = copy.deepcopy(tiers) if isinstance(tiers, dict) else {}
    excluded = (profile or {}).get("excludedModels")
    result["excludedModels"] = [item for item in excluded if isinstance(item, str)] if isinstance(excluded, list) else []
    return result


def provider_policy(bundle: Path, home: Path, config_root: Path, existing: dict, gateway_url: str | None) -> tuple[bytes, dict | None]:
    """Return (policy bytes, fleet to carry lane choices from; None = the
    installed fleet).

    A provider policy and the lane pins describe one provider's models. When
    an explicit --gateway-url names another endpoint than the live one, the
    installed policy and pins are not carried: the policy and choices saved
    with an agentfleet profile for that endpoint are used, else the generic
    shipped policy with no pins. A profile saved before policies were stored
    per profile keeps today's behaviour.
    """
    if gateway_url:
        env = existing.get("env") if isinstance(existing.get("env"), dict) else {}
        old_url = env.get("ANTHROPIC_BASE_URL")
        if same_endpoint(old_url, gateway_url):
            return merged_policy_bytes(bundle, config_root), None
        # A profile with a valid policy wins over older ones for the same
        # endpoint; only when none has one does a legacy profile (saved
        # before policies were per profile) keep today's behaviour.
        legacy = False
        for profile in saved_gateway_profiles(home, gateway_url):
            if "policy" not in profile:
                legacy = True
                continue
            try:
                policy = provider_catalog.validate_policy(copy.deepcopy(profile["policy"]))
            except provider_catalog.CatalogError as exc:
                print(f"claude-agents-config: agentfleet profile '{profile['name']}' has an invalid provider policy ({exc}); ignoring it", file=sys.stderr)
                continue
            print(f"Gateway {gateway_url}: using the provider policy and lane choices saved in agentfleet profile '{profile['name']}'.")
            return json_bytes(policy), rebased_fleet(existing_fleet_map(home, config_root), profile)
        if not legacy:
            live = existing_fleet_map(home, config_root)
            generic = source_bytes(bundle, PROVIDER_POLICY_PATH)
            installed_policy = config_root / "delegate-skills" / "provider-policy.json"
            try:
                replaced = installed_policy.is_file() and json.loads(installed_policy.read_text(encoding="utf-8")) != json.loads(generic.decode("utf-8"))
            except (OSError, UnicodeError, json.JSONDecodeError):
                replaced = True
            if replaced:
                print(
                    f"Gateway changed ({old_url or 'no gateway'} -> {gateway_url}): not carrying the previous provider's model families; "
                    "using the generic policy (all models approved). "
                    "Tip: agentfleet add NAME --gateway-url URL switches providers without reinstalling."
                )
            return generic, rebased_fleet(live, None)
    return merged_policy_bytes(bundle, config_root), None


