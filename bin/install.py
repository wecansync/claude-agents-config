def picker_row_key(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def bundle_owned_picker_rows(previous: dict[str, dict], previous_metadata: dict) -> set[str]:
    """Return exact picker rows introduced by a prior bundle profile.

    Picker rows have no intrinsic marker. New metadata carries an explicit
    ownedRows list and preserves it across updates, so a row added later by a
    user is not reclassified as installer-owned. The difference fallback keeps
    older metadata migrations conservative.
    """
    if previous_metadata.get("profile") != "gateway":
        return set()
    entry = previous.get("value:modelPicker")
    if not isinstance(entry, dict):
        return set()
    owned_rows = entry.get("ownedRows")
    if isinstance(owned_rows, list) and all(isinstance(row, str) for row in owned_rows):
        return set(owned_rows)
    installed = entry.get("installed") if isinstance(entry.get("installed"), dict) else {}
    before = entry.get("before") if entry.get("beforePresent") and isinstance(entry.get("before"), dict) else {}
    installed_rows = installed.get("options") if isinstance(installed.get("options"), list) else []
    before_rows = before.get("options") if isinstance(before.get("options"), list) else []
    remaining: dict[str, int] = {}
    for row in before_rows:
        key = picker_row_key(row)
        remaining[key] = remaining.get(key, 0) + 1
    owned: set[str] = set()
    for row in installed_rows:
        key = picker_row_key(row)
        count = remaining.get(key, 0)
        if count:
            remaining[key] = count - 1
        else:
            owned.add(key)
    return owned


def previous_journal_map(previous: dict) -> dict[str, dict]:
    result = {}
    for entry in previous.get("settingsJournal", []) if isinstance(previous.get("settingsJournal"), list) else []:
        if isinstance(entry, dict) and isinstance(entry.get("id"), str):
            result[entry["id"]] = entry
    return result


def before_for(identity: str, current: object, previous: dict[str, dict]) -> tuple[bool, object]:
    old = previous.get(identity)
    if old and "beforePresent" in old:
        return bool(old.get("beforePresent")), copy.deepcopy(old.get("before"))
    return (current is not ABSENT), copy.deepcopy(current) if current is not ABSENT else None


# Journal entries whose installed value is a credential keep only a digest:
# ownership checks just need "unchanged since install", and the journal must
# not hold a copy of the token after the user switches away from it.
SECRET_JOURNAL_IDS = {"value:env:ANTHROPIC_AUTH_TOKEN"}
API_KEY_JOURNAL_ID = "value:env:ANTHROPIC_API_KEY"


def secret_digest(value: object) -> dict:
    return {"redactedSha256": hashlib.sha256(str(value).encode("utf-8")).hexdigest()}


def redacted_equal(current: object, installed: object) -> bool:
    """Equality where a redacted journal value matches by digest."""
    if isinstance(installed, dict) and set(installed) == {"redactedSha256"}:
        return isinstance(current, str) and secret_digest(current) == installed
    if isinstance(installed, dict):
        return isinstance(current, dict) and set(current) == set(installed) and all(redacted_equal(current[key], value) for key, value in installed.items())
    return current == installed


def redact_journal_secrets(journal: dict[str, dict]) -> None:
    """Replace credentials that versions before 2.0.5 journaled in
    plaintext, in the per-key entry and in the whole-env entry."""
    for identity, entry in list(journal.items()):
        installed = entry.get("installed")
        if identity in SECRET_JOURNAL_IDS and isinstance(installed, str):
            journal[identity] = {**entry, "installed": secret_digest(installed)}
        elif identity == "value:env" and isinstance(installed, dict) and isinstance(installed.get("ANTHROPIC_AUTH_TOKEN"), str):
            journal[identity] = {**entry, "installed": {**installed, "ANTHROPIC_AUTH_TOKEN": secret_digest(installed["ANTHROPIC_AUTH_TOKEN"])}}


def current_matches_installed(current: object, entry: dict) -> bool:
    return redacted_equal(current, entry.get("installed"))


def record_value_journal(
    journal: dict[str, dict], identity: str, path: list[str], current: object, installed: object, previous: dict[str, dict]
) -> None:
    before_present, before = before_for(identity, current, previous)
    old = previous.get(identity)
    installed_present = installed is not ABSENT
    journal[identity] = {
        "id": identity,
        "kind": "value",
        "path": path,
        "beforePresent": before_present,
        "before": before,
        "installedPresent": installed_present,
        "installed": copy.deepcopy(installed) if installed_present else None,
    }
    if identity in SECRET_JOURNAL_IDS and installed_present:
        journal[identity]["installed"] = secret_digest(installed)
    if old and old.get("beforePresent") is False:
        journal[identity]["before"] = None


def get_nested(value: dict, path: list[str]) -> object:
    current: object = value
    for key in path:
        if not isinstance(current, dict) or key not in current:
            return ABSENT
        current = current[key]
    return current


def compact_number(value: object) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        number = value
    elif isinstance(value, str) and re.fullmatch(r"[0-9]+", value):
        number = int(value)
    else:
        return None
    return number if 100_000 <= number <= 1_000_000 else None


def prior_installed_matches(prior: dict[str, dict], identity: str, current: object) -> bool:
    entry = prior.get(identity)
    return bool(
        entry
        and entry.get("installedPresent", True)
        and current is not ABSENT
        and current == entry.get("installed")
    )


def merge_compaction_controls(desired: dict, existing: dict, prior: dict[str, dict], journal: dict[str, dict]) -> None:
    """Keep the two global compaction controls valid and ownership-aware.

    Claude Code accepts one global window, so an update must never refresh one
    control while preserving a later edit to the other.  A mismatched pair is
    refused unless it is the exact legacy pair recorded as bundle-installed;
    a one-sided value is mirrored so a deliberate user value remains intact.
    """
    top_identity = "value:autoCompactWindow"
    env_identity = "value:env:CLAUDE_CODE_AUTO_COMPACT_WINDOW"
    top_current = existing.get("autoCompactWindow", ABSENT)
    existing_env = existing.get("env") if isinstance(existing.get("env"), dict) else {}
    env_current = existing_env.get("CLAUDE_CODE_AUTO_COMPACT_WINDOW", ABSENT)
    top_number = compact_number(top_current) if top_current is not ABSENT else None
    env_number = compact_number(env_current) if env_current is not ABSENT else None

    def set_top(value: int) -> None:
        current = get_nested(existing, ["autoCompactWindow"])
        if current != value:
            record_value_journal(journal, top_identity, ["autoCompactWindow"], current, value, prior)
        desired["autoCompactWindow"] = value

    def set_env(value: int) -> None:
        current = get_nested(existing, ["env", "CLAUDE_CODE_AUTO_COMPACT_WINDOW"])
        installed = str(value)
        if current != installed:
            record_value_journal(journal, env_identity, ["env", "CLAUDE_CODE_AUTO_COMPACT_WINDOW"], current, installed, prior)
        desired.setdefault("env", {})["CLAUDE_CODE_AUTO_COMPACT_WINDOW"] = installed

    if top_current is ABSENT and env_current is ABSENT:
        if top_identity in prior or env_identity in prior:
            fail("both compaction controls are missing after an earlier install; set autoCompactWindow and CLAUDE_CODE_AUTO_COMPACT_WINDOW to the same value before updating")
        set_top(AUTO_COMPACT_WINDOW)
        set_env(AUTO_COMPACT_WINDOW)
        return

    if top_current is ABSENT or env_current is ABSENT:
        number = env_number if top_current is ABSENT else top_number
        if number is None:
            fail("compaction controls contain an invalid token count; set autoCompactWindow and CLAUDE_CODE_AUTO_COMPACT_WINDOW to matching integers from 100000 to 1000000 before updating")
        # The present value is a deliberate user choice unless both controls
        # still prove bundle-owned.  Mirroring it avoids a post-write doctor
        # failure without silently changing that choice.
        if top_current is ABSENT:
            set_top(number)
        if env_current is ABSENT:
            set_env(number)
        return

    if top_number is None or env_number is None:
        fail("compaction controls contain an invalid token count; set autoCompactWindow and CLAUDE_CODE_AUTO_COMPACT_WINDOW to matching integers from 100000 to 1000000 before updating")

    pair_owned = prior_installed_matches(prior, top_identity, top_current) and prior_installed_matches(prior, env_identity, env_current)
    if top_number != env_number:
        legacy_owned = (
            top_number == LEGACY_AUTO_COMPACT_WINDOW
            and env_number == int(LEGACY_AUTO_COMPACT_ENV)
            and pair_owned
        )
        if not legacy_owned:
            fail("autoCompactWindow and CLAUDE_CODE_AUTO_COMPACT_WINDOW differ; set both controls to the same token count before updating")
        set_top(AUTO_COMPACT_WINDOW)
        set_env(AUTO_COMPACT_WINDOW)
    elif pair_owned and top_number != AUTO_COMPACT_WINDOW:
        # Refresh an unchanged bundle-owned pair atomically.  If either side
        # was edited, pair_owned is false and both user values are preserved.
        set_top(AUTO_COMPACT_WINDOW)
        set_env(AUTO_COMPACT_WINDOW)


def set_nested(value: dict, path: list[str], item: object) -> None:
    current = value
    for key in path[:-1]:
        child = current.get(key)
        if not isinstance(child, dict):
            child = {}
            current[key] = child
        current = child
    current[path[-1]] = copy.deepcopy(item)


def delete_nested(value: dict, path: list[str]) -> None:
    current: object = value
    for key in path[:-1]:
        if not isinstance(current, dict) or key not in current:
            return
        current = current[key]
    if isinstance(current, dict):
        current.pop(path[-1], None)


def windows_command(*parts: str) -> str:
    # Quote every part unconditionally. list2cmdline only quotes parts with
    # spaces, but bare "C:\..." paths lose their backslashes when Claude Code
    # runs the hook through Git Bash or PowerShell ("C:\a" parses as "C:a"),
    # so the executable is never found. Double quotes are literal-safe under
    # cmd.exe, bash, and PowerShell alike, and '"' cannot appear in a Windows
    # path, so no escape handling is required.
    return " ".join(f'"{part}"' for part in parts)


# The script each hook kind currently invokes. Single source of truth for
# hook_command_for and retired_hook_script_for_kind (below), which flags a
# marker-bearing hook that still names a script this bundle has since
# retired for its kind (per LEGACY_FRAGMENT_KIND) so it never keeps such a
# hook wired to a script that no longer exists after this same run deletes it.
HOOK_SCRIPT_FOR_KIND = {
    "route": "route-to-fleet.py",
    "statusline": "subagent-statusline.py",
    "model-sync": "sync-provider-models.mjs",
    "model-context": "sync-model-context.py",
    "fleet-reconcile": "fleet-reconcile.py",
    "auto-update": "agentfleet.py",
}


def hook_command_for(kind: str, claude_dir: Path, config_root: Path | None = None) -> str:
    script = claude_dir / HOOK_SCRIPT_FOR_KIND[kind]
    if kind == "model-sync":
        runtime = node_path(require=True)
        # --drift is intentionally only ever passed here, never by any other
        # invocation (e.g. the shell `claude` wrapper some setups add, which
        # runs this same script pre-launch without the flag). The drift
        # detector's own dedup skips a run once models_hash is unchanged, so
        # a flagless run before the hook would silently consume the one
        # notice the SessionStart hook needed to surface via additionalContext.
        # --python pins the interpreter the drift subprocess uses to the
        # same one the installer resolved for every other managed python
        # hook (sys.executable), instead of letting it fall back to whatever
        # "python3" resolves to on the session's PATH at hook run time.
        parts = [str(runtime), str(script), "--quiet", "--drift", "--python", sys.executable]
        if config_root is not None:
            parts.extend(["--config-home", str(config_root)])
    else:
        parts = [sys.executable, str(script), "--home", str(claude_dir.parent)]
        if config_root is not None:
            parts.extend(["--config-home", str(config_root)])
        if kind == "auto-update":
            # --home/--config-home are main-parser options and must precede
            # the "auto-update" subcommand token; argparse does not accept
            # them after it once the subparser has taken over.
            parts.extend(["auto-update", "--hook"])
    if os.name == "nt":
        return windows_command(*parts)
    return " ".join(shlex.quote(str(part)) for part in parts)


def hook_marker(kind: str) -> str:
    # One comment form for every platform: Claude Code runs hook commands via
    # sh on POSIX, Git Bash on Windows, or PowerShell when Git Bash is absent
    # -- never cmd.exe. The old Windows "& rem" form backgrounds the command
    # and exits 127 under bash ("rem: command not found") and is a parse
    # error under PowerShell, so marked hooks never ran there. "#" comments
    # out the marker under sh, bash, and PowerShell alike.
    return " # " + MARKER + kind


@contextmanager
def target_lock(home: Path):
    """Serialize every managed writer with the shared portable lock.

    Only the installer creates the lock's parent (``home/.claude``): it may
    be racing to create that directory for the very first time, after its
    own preflight has already rejected a symlinked home or bundle.
    """
    fd, lock_path = acquire_shared_lock(home, timeout=None, create_parent=True)
    if fd is None:
        fail(f"cannot acquire target lock: {lock_path}")
    try:
        yield
    finally:
        release_shared_lock(fd, lock_path)


def optional_agent_brain_available() -> bool:
    return shutil.which("agent-brain") is not None


def agent_brain_command(action: str) -> str:
    runtime = shutil.which("agent-brain")
    if not runtime:
        return ""
    parts = (runtime, "hook", action)
    if os.name == "nt":
        return windows_command(*parts)
    return " ".join(shlex.quote(str(part)) for part in parts)


def platform_hook_template(home: Path, config_root: Path, template: dict, enable_discovery: bool) -> dict:
    value = copy.deepcopy(template)
    hooks = value.get("hooks") if isinstance(value.get("hooks"), dict) else {}
    desired: dict[str, list[dict]] = {}
    for event, entries in hooks.items():
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if not isinstance(entry, dict) or not isinstance(entry.get("hooks"), list):
                continue
            inner = []
            for hook in entry["hooks"]:
                if not isinstance(hook, dict):
                    continue
                command = str(hook.get("command", ""))
                marker = re.search(r"claude-agents-config:([a-z0-9-]+)", command)
                if not marker:
                    continue
                kind = marker.group(1)
                if kind == "agent-brain" and not optional_agent_brain_available():
                    continue
                if kind == "route":
                    command = hook_command_for("route", home / ".claude") + hook_marker("route")
                elif kind == "statusline":
                    command = hook_command_for("statusline", home / ".claude") + hook_marker("statusline")
                elif kind == "model-sync":
                    # Always wired: it does nothing until gateway discovery is
                    # enabled, and a native install can later switch to a
                    # gateway profile with `agentfleet add --use`.
                    command = hook_command_for("model-sync", home / ".claude", config_root) + hook_marker("model-sync")
                elif kind == "model-context":
                    command = hook_command_for("model-context", home / ".claude", config_root) + hook_marker("model-context")
                elif kind == "auto-update":
                    command = hook_command_for("auto-update", home / ".claude", config_root) + hook_marker("auto-update")
                elif kind == "fleet-reconcile":
                    if not enable_discovery:
                        continue
                    command = " ".join(shlex.quote(str(part)) for part in (
                        sys.executable,
                        home / ".claude" / "fleet-reconcile.py",
                        "--home", home,
                        "--config-home", config_root,
                        "--policy", config_root / "delegate-skills" / "provider-policy.json",
                        "--catalog", home / ".claude" / "cache" / MODEL_CACHE_NAME,
                        "--session-start",
                    )) + hook_marker("fleet-reconcile")
                elif kind == "agent-brain":
                    match = re.search(r"agent-brain\s+hook\s+([A-Za-z0-9_-]+)", command)
                    if not match:
                        continue
                    command = agent_brain_command(match.group(1))
                    if not command:
                        continue
                    command += hook_marker("agent-brain")
                else:
                    continue
                copied = copy.deepcopy(hook)
                copied["command"] = command
                inner.append(copied)
            if inner:
                desired.setdefault(event, []).append({**{k: copy.deepcopy(v) for k, v in entry.items() if k != "hooks"}, "hooks": inner})
    value["hooks"] = desired
    status = value.get("subagentStatusLine")
    if isinstance(status, dict):
        command = hook_command_for("statusline", home / ".claude") + hook_marker("statusline")
        value["subagentStatusLine"] = {**status, "command": command}
    return value


def hook_suffix(command: str) -> str | None:
    marker = re.search(r"claude-agents-config:([a-z0-9-]+)", command)
    return marker.group(1) if marker else None


def retired_hook_kind(command: object) -> str | None:
    """The marker kind that supersedes this unmarked legacy command, or None
    if it does not match any known legacy fragment. hook_suffix() cannot find
    these by marker since they predate the marker convention (or, for
    fleet-model-proposal.py, were never installer-managed)."""
    if not isinstance(command, str):
        return None
    for fragment, kind in LEGACY_FRAGMENT_KIND.items():
        if fragment in command:
            return kind
    return None


def normalized_hook_command(command: object) -> str:
    """A hook command reduced to a form comparable across quoting and marker
    conventions: the trailing claude-agents-config marker, in either its
    current " # ..." form or the pre-2.0 Windows " & rem ..." form, is
    stripped; the double quotes windows_command wraps every argument in are
    removed; and internal whitespace is collapsed. Two commands equal once
    normalized differ only cosmetically -- e.g. a tool outside the installer
    re-quoted settings.json, or the journal recorded the command back when a
    different marker convention was in use -- and are the same installed
    command for ownership purposes, in whichever direction (settings.json or
    the journal) still carries the older form."""
    if not isinstance(command, str):
        return ""
    text = re.sub(r"\s*(?:&\s*rem|#)\s*" + re.escape(MARKER) + r"[a-z0-9-]+\s*$", "", command)
    text = text.replace('"', "")
    return " ".join(text.split())


def retired_hook_script_for_kind(kind: str, command: object) -> str | None:
    """The retired legacy script this marker-bearing command still names for
    kind's hook, or None. A command can be a genuine, deliberate user edit
    (see clean_hook_groups) and still be unsafe to keep verbatim: if it
    names a script LEGACY_FRAGMENT_KIND maps to kind but HOOK_SCRIPT_FOR_KIND
    no longer does, the bundle has retired that script for this kind (e.g.
    sync-omniroute-models.mjs, superseded by sync-provider-models.mjs for
    model-sync), and this same run deletes it -- keeping the edit wired would
    guarantee a broken hook."""
    if not isinstance(command, str):
        return None
    current_script = HOOK_SCRIPT_FOR_KIND.get(kind)
    if current_script is None:
        return None
    for fragment, frag_kind in LEGACY_FRAGMENT_KIND.items():
        if frag_kind != kind or fragment not in command:
            continue
        script_name = fragment.rsplit("/", 1)[-1].rsplit("\\", 1)[-1]
        if script_name and script_name != current_script:
            return script_name
    return None


def incoming_kinds_by_event(incoming: dict) -> dict[str, set[str]]:
    result: dict[str, set[str]] = {}
    for event, entries in incoming.items():
        kinds: set[str] = set()
        for group in entries if isinstance(entries, list) else []:
            hooks = group.get("hooks") if isinstance(group, dict) else None
            for hook in hooks if isinstance(hooks, list) else []:
                command = hook.get("command") if isinstance(hook, dict) else None
                suffix = hook_suffix(command) if isinstance(command, str) else None
                if suffix:
                    kinds.add(suffix)
        result[event] = kinds
    return result


def clean_hook_groups(existing: dict, incoming: dict, journal: dict[str, dict], previous: dict[str, dict], notices: list[str]) -> dict:
    result = copy.deepcopy(existing)
    prior_commands = {
        str(entry.get("installed"))
        for entry in previous.values()
        if isinstance(entry, dict) and entry.get("kind") == "hook" and isinstance(entry.get("installed"), str)
    }
    incoming_kinds = incoming_kinds_by_event(incoming)
    edited_suffixes: set[str] = set()
    legacy_restores: dict[tuple[str, str], list[dict]] = {}
    for event in list(result):
        entries = result.get(event)
        if not isinstance(entries, list):
            continue
        cleaned_entries = []
        for entry in entries:
            if not isinstance(entry, dict) or not isinstance(entry.get("hooks"), list):
                cleaned_entries.append(entry)
                continue
            kept_hooks = []
            for hook in entry["hooks"]:
                command = hook.get("command") if isinstance(hook, dict) else None
                suffix = hook_suffix(command) if isinstance(command, str) else None
                if suffix is None:
                    retired_kind = retired_hook_kind(command)
                    if retired_kind and retired_kind in incoming_kinds.get(event, set()):
                        # An unmarked legacy hook is only dropped when a
                        # marker-bearing replacement of the same kind is
                        # actually being installed for this event this run;
                        # otherwise it would be deleted with nothing to take
                        # over its job (e.g. agent-brain missing from PATH,
                        # or discovery disabled so model-sync is not wired).
                        if retired_kind == "model-sync":
                            legacy_restores.setdefault((event, retired_kind), []).append(copy.deepcopy(hook))
                        continue
                    kept_hooks.append(hook)
                elif command in prior_commands:
                    # Remove the exact previous bundle command before adding the
                    # refreshed command below.
                    continue
                elif f"hook:{event}:{suffix}" in previous:
                    identity = f"hook:{event}:{suffix}"
                    old_installed = previous[identity].get("installed")
                    retired_script = retired_hook_script_for_kind(suffix, command)
                    if isinstance(old_installed, str) and normalized_hook_command(command) == normalized_hook_command(old_installed):
                        # Equal to the previously installed command once
                        # quoting and marker-style differences are stripped
                        # away (e.g. something outside the installer
                        # re-quoted settings.json, or this journal entry
                        # predates the "# marker" convention). Treat exactly
                        # like the exact-match branch above: drop it so the
                        # refreshed command below takes its place.
                        continue
                    elif retired_script:
                        # A genuine edit, but one that still names a script
                        # this bundle has retired for this kind, and this
                        # same run deletes that script. Keeping the edit
                        # verbatim would leave a hook that fails every
                        # session, so it is replaced like the cases above.
                        notices.append(
                            f"  refresh: hook:{event}:{suffix} pointed at the retired {retired_script}; "
                            "replacing the edited command with the refreshed hook "
                            "(the pre-update settings.json is already in the backup snapshot)"
                        )
                        continue
                    else:
                        # A marker-bearing command changed after installation
                        # for a reason other than the two above. Treat it as
                        # a later user edit and never overwrite it.
                        edited_suffixes.add(f"{event}:{suffix}")
                        kept_hooks.append(hook)
                else:
                    # Legacy marker-bearing commands are safe to migrate.
                    continue
            if kept_hooks:
                copied = copy.deepcopy(entry)
                copied["hooks"] = kept_hooks
                cleaned_entries.append(copied)
        if cleaned_entries:
            result[event] = cleaned_entries
        else:
            del result[event]

    for event, entries in incoming.items():
        for group in entries if isinstance(entries, list) else []:
            hooks = group.get("hooks", []) if isinstance(group, dict) else []
            for hook in hooks if isinstance(hooks, list) else []:
                command = hook.get("command") if isinstance(hook, dict) else None
                if not isinstance(command, str):
                    continue
                suffix = hook_suffix(command)
                if suffix is None or f"{event}:{suffix}" in edited_suffixes:
                    continue
                identity = f"hook:{event}:{suffix}"
                old = previous.get(identity)
                if old and old.get("beforePresent") is False:
                    before_present, before = False, None
                else:
                    before_present, before = before_for(identity, ABSENT, previous)
                journal[identity] = {
                    "id": identity,
                    "kind": "hook",
                    "event": event,
                    "command": command,
                    "beforePresent": before_present,
                    "before": before,
                    "installed": command,
                }
                result.setdefault(event, []).append({**{k: copy.deepcopy(v) for k, v in group.items() if k != "hooks"}, "hooks": [copy.deepcopy(hook)]})
    for (event, kind), hooks in legacy_restores.items():
        for index, hook in enumerate(hooks):
            journal[f"hook:{event}:legacy-{kind}-{index}"] = {
                "id": f"hook:{event}:legacy-{kind}-{index}",
                "kind": "hook",
                "event": event,
                "command": hook.get("command", ""),
                "beforePresent": True,
                "before": None,
                "installedPresent": False,
                "installed": None,
                "restore": hook,
            }
    return result


