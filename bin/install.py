def check_parent_conflicts(specs: dict[Path, tuple[bytes, int, str]], meta: dict, bundle: Path, force: bool) -> list[Path]:
    conflicts = []
    for path, (data, _, _) in specs.items():
        if not lexists(path):
            continue
        if path.is_dir() or path.is_symlink():
            conflicts.append(path)
            continue
        if not owned_existing(path, read_bytes(path), meta, bundle, specs) and not force:
            conflicts.append(path)
    return conflicts


def write_all(fd: int, data: bytes) -> None:
    view = memoryview(data)
    while view:
        written = os.write(fd, view)
        if written <= 0:
            raise OSError("short write")
        view = view[written:]


def fsync_dir(path: Path) -> None:
    if os.name == "nt":
        return
    try:
        fd = os.open(str(path), os.O_RDONLY)
    except OSError:
        return
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def ensure_no_symlink_parent(path: Path) -> None:
    """Refuse to follow a symlink in any existing parent directory."""
    current = path.parent
    missing: list[Path] = []
    while not current.exists() and current != current.parent:
        missing.append(current)
        current = current.parent
    while True:
        if current.is_symlink():
            fail(f"refusing to write through symlinked parent directory: {current}")
        if current == current.parent:
            break
        current = current.parent


def replace_with_retry(source: Path, target: Path, attempts: int = 6) -> None:
    """os.replace with bounded retries for transient filesystem locks.

    Real-time antivirus, file watchers, and indexers routinely hold a target
    open for milliseconds, denying the replacement with EPERM/EACCES
    (WinError 5 on Windows). Retry those briefly; anything else raises
    immediately so genuine failures still surface fast.
    """
    delay = 0.1
    for attempt in range(attempts):
        try:
            os.replace(source, target)
            return
        except OSError as error:
            transient = error.errno in (errno.EPERM, errno.EACCES, errno.EBUSY) or getattr(error, "winerror", None) == 5
            if not transient or attempt + 1 >= attempts:
                raise
            time.sleep(delay)
            delay *= 2


def atomic_write(path: Path, data: bytes, mode: int) -> None:
    ensure_no_symlink_parent(path)
    if path.parent.exists() and not path.parent.is_dir():
        fail(f"cannot create parent directory because it is a file: {path.parent}")
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    temp = Path(temp_name)
    try:
        write_all(fd, data)
        os.fsync(fd)
        if os.name != "nt":
            os.fchmod(fd, mode)
        os.close(fd)
        replace_with_retry(temp, path)
        if os.name != "nt":
            os.chmod(path, mode)
        fsync_dir(path.parent)
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            temp.unlink()
        except OSError:
            pass
        raise


def snapshot_paths(paths: list[Path], root: Path, label: str) -> Path:
    root.mkdir(parents=True, exist_ok=False)
    os.chmod(root, 0o700)
    files = root / "files"
    files.mkdir(mode=0o700)
    records = []
    for index, path in enumerate(sorted(set(paths), key=str)):
        existed = lexists(path)
        record = {"path": str(path), "existed": bool(existed)}
        if existed:
            if path.is_dir() or path.is_symlink():
                fail(f"cannot snapshot directory or symlink target: {path}")
            data = read_bytes(path)
            payload = files / f"{index:04d}.bin"
            payload.write_bytes(data)
            os.chmod(payload, 0o600)
            record.update({"backup": str(payload.relative_to(root)), "mode": stat.S_IMODE(path.stat().st_mode), "sha256": bytes_sha256(data)})
        records.append(record)
    manifest = {"marker": MARKER, "format": "claude-agents-config.backup.v2", "label": label, "records": records}
    atomic_write(root / "backup.json", json_bytes(manifest), 0o600)
    os.chmod(root, 0o700)
    fsync_dir(root)
    return root


def create_backup(paths: list[Path], home: Path, dry: bool, label: str) -> Path | None:
    if dry:
        return None
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S")
    parent = home / ".claude" / "backups" / "claude-agents-config"
    parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(parent, 0o700)
    root = parent / f"{stamp}Z"
    suffix = 0
    while root.exists():
        suffix += 1
        root = parent / f"{stamp}Z-{suffix}"
    return snapshot_paths(paths, root, label)


def restore_snapshot(backup: Path, home: Path, bin_dir: Path, config_root: Path, write: bool = True) -> None:
    manifest = load_json(backup / "backup.json", "backup manifest")
    if manifest.get("marker") != MARKER or manifest.get("format") != "claude-agents-config.backup.v2":
        fail(f"backup manifest marker or format is invalid: {backup / 'backup.json'}")
    records = manifest.get("records")
    if not isinstance(records, list) or not records:
        fail(f"backup manifest has no records: {backup / 'backup.json'}")

    prepared: list[tuple[Path, bool, bytes | None, int | None]] = []
    seen_targets: set[str] = set()
    seen_payloads: set[str] = set()
    backup_root = backup.resolve()
    for record in records:
        if not isinstance(record, dict) or not isinstance(record.get("path"), str):
            fail("backup manifest has an invalid path")
        path = Path(record["path"])
        if str(path) in seen_targets:
            fail(f"backup manifest repeats target path: {path}")
        seen_targets.add(str(path))
        if not path.is_absolute() or not allowed_target(path, home, bin_dir, config_root):
            fail(f"backup path escapes target roots: {path}")
        existed = record.get("existed")
        if not isinstance(existed, bool):
            fail(f"backup record has an invalid existed flag: {path}")
        if existed:
            backup_name = record.get("backup")
            digest = record.get("sha256")
            mode = record.get("mode")
            if not isinstance(backup_name, str) or not backup_name or not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
                fail(f"backup record lacks a valid payload/hash: {path}")
            # Any permission bits are valid for the *original* file: a user's
            # read-only (0444) file must still be restorable. The payload's own
            # 0600 mode is checked separately.
            if not isinstance(mode, int) or isinstance(mode, bool) or stat.S_IMODE(mode) != mode or not 0 <= mode <= 0o777:
                fail(f"backup record has an invalid mode: {path}")
            relative_payload = Path(backup_name)
            if relative_payload.is_absolute() or ".." in relative_payload.parts or relative_payload.parts[:1] != ("files",):
                fail(f"backup payload path is unsafe: {backup_name}")
            if backup_name in seen_payloads:
                fail(f"backup manifest repeats payload: {backup_name}")
            seen_payloads.add(backup_name)
            payload = backup / relative_payload
            if not payload.is_file() or payload.is_symlink() or backup_root not in payload.resolve().parents:
                fail(f"backup payload is invalid: {payload}")
            if os.name != "nt" and stat.S_IMODE(payload.stat().st_mode) != 0o600:
                fail(f"backup payload mode is not 0o600; refusing restore: {payload}")
            data = payload.read_bytes()
            if bytes_sha256(data) != digest:
                fail(f"backup payload checksum mismatch; refusing restore: {payload}")
            prepared.append((path, True, data, mode))
        else:
            prepared.append((path, False, None, None))

    # All backup records, hashes, payloads, and modes are verified above before
    # the first target mutation. A corrupt later record cannot yield a partial
    # restore of earlier targets.
    if not write:
        return
    for path, existed, data, mode in prepared:
        if existed:
            assert data is not None and mode is not None
            atomic_write(path, data, mode)
        elif lexists(path):
            if path.is_symlink():
                fail(f"refusing to remove unexpected symlink during rollback: {path}")
            if path.is_dir():
                try:
                    path.rmdir()
                except OSError as exc:
                    fail(f"refusing to remove non-empty directory during rollback: {path} ({exc})")
            else:
                path.unlink()
            fsync_dir(path.parent)


def stage_and_commit(specs: dict[Path, tuple[bytes, int, str]], backup: Path) -> None:
    """Prepare each target on its own filesystem, then replace it atomically.

    A single staging directory under the backup root is unsafe when the backup
    tree and a configured XDG/prefix root live on different filesystems.  Each
    target receives a sibling temporary file, so ``os.replace`` remains an
    atomic same-filesystem operation.  The backup is still the recovery source
    if a later target or doctor check fails.
    """
    staged: list[tuple[Path, Path, int]] = []
    try:
        for path, (data, mode, _) in sorted(specs.items(), key=lambda item: str(item[0])):
            ensure_no_symlink_parent(path)
            if lexists(path) and path.is_dir():
                fail(f"refusing to replace directory: {path}")
            path.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
            fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.stage-", dir=str(path.parent))
            temp = Path(temp_name)
            try:
                write_all(fd, data)
                os.fsync(fd)
                if os.name != "nt":
                    os.fchmod(fd, mode)
                os.close(fd)
                fd = -1
                os.chmod(temp, mode)
            except Exception:
                try:
                    os.close(fd)
                except OSError:
                    pass
                temp.unlink(missing_ok=True)
                raise
            staged.append((path, temp, mode))
        # Every temporary file is fully written before the first replacement.
        for path, staged_path, mode in staged:
            ensure_no_symlink_parent(path)
            replace_with_retry(staged_path, path)
            if os.name != "nt":
                os.chmod(path, mode)
            fsync_dir(path.parent)
    finally:
        for _, staged_path, _ in staged:
            try:
                staged_path.unlink()
            except OSError:
                pass


