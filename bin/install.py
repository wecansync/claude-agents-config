def carry_lane_choices(bundle_fleet: dict, existing: dict, *, drop_shipped_pins: bool = False) -> dict:
    """Keep the user's per-lane model choices across an update.

    Old lane names are mapped to their successors; lanes the bundle no longer
    ships are dropped (their generated agents are pruned by the installer).
    Model-tier labels written by the setup wizard are kept as well. With
    drop_shipped_pins (an update from before 2.0.1), preferences 1.0.0 shipped
    as defaults are dropped once instead of being carried as user choices.
    """
    shipped = reconcile_module().is_shipped_1_0_preference
    result = copy.deepcopy(bundle_fleet)
    old_lanes = existing.get("lanes") if isinstance(existing.get("lanes"), dict) else {}
    for old_name, old_config in old_lanes.items():
        if not isinstance(old_config, dict):
            continue
        name = LANE_RENAMES.get(old_name, old_name)
        target = result["lanes"].get(name)
        if not isinstance(target, dict):
            continue
        # A renamed lane only fills its successor when the successor has no
        # choices of its own under the new name.
        if old_name != name and name in old_lanes:
            continue
        for field in CARRIED_LANE_FIELDS:
            value = old_config.get(field)
            if field == "model" and isinstance(value, str) and value:
                target["model"] = value
            elif field in {"preferred", "fallbacks"} and isinstance(value, list):
                if field == "preferred" and drop_shipped_pins and shipped(name, value):
                    continue
                values = [item for item in value if isinstance(item, str) and item]
                if values:
                    target[field] = values
    # Lanes the user added (e.g. via /fleet-setup) are theirs and stay; the
    # installer renders their agents with the generator after committing.
    bundle_names = set(bundle_fleet.get("lanes", {}))
    for name, config in old_lanes.items():
        if (
            name in bundle_names or name in LANE_RENAMES or name in RETIRED_LANES
            or not isinstance(config, dict) or config.get("implementer") != "claude"
            or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name)
        ):
            continue
        result["lanes"][name] = copy.deepcopy(config)
    tiers = existing.get("modelTiers")
    if isinstance(tiers, dict):
        result["modelTiers"] = {**result.get("modelTiers", {}), **copy.deepcopy(tiers)}
    excluded = [item for item in existing.get("excludedModels") or [] if isinstance(item, str) and item.strip()]
    if excluded:
        result["excludedModels"] = excluded
    return result


def discover_gateway_rows(home: Path, url: str | None, token: str | None, existing: dict) -> tuple[list[dict] | None, str]:
    """Return (rows, source). Rows are raw provider catalog rows."""
    if isinstance(url, str) and url and isinstance(token, str) and token:
        rows, complete, error = provider_catalog.fetch_catalog(url, token, timeout=8.0)
        if complete:
            return rows, "live"
        cache_dir = home / ".claude" / "cache"
        for name in (MODEL_CACHE_NAME, LEGACY_MODEL_CACHE_NAME):
            path = cache_dir / name
            if not path.is_file():
                continue
            try:
                cached = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, UnicodeError, json.JSONDecodeError):
                continue
            # An offline update may reuse an older cache for the same
            # endpoint and account; a fresh reconcile corrects it at startup.
            rows = provider_catalog.cache_rows(cached, url, token, ttl=30 * 24 * 60 * 60)
            if rows:
                return rows, "cache"
    picker = existing.get("modelPicker") if isinstance(existing.get("modelPicker"), dict) else {}
    options = picker.get("options") if isinstance(picker.get("options"), list) else []
    rows = [
        {"id": row["model"], "description": row.get("description", "")}
        for row in options
        if isinstance(row, dict) and isinstance(row.get("model"), str) and "gateway" in str(row.get("description", "")).lower()
    ]
    if rows:
        return rows, "existing picker"
    return None, "unavailable"


def gateway_profile(bundle_fleet: dict, template: dict, rows: list[dict], policy: dict) -> tuple[dict, dict]:
    """Resolve lanes against a gateway catalog and build the matching template."""
    reconcile = reconcile_module()
    fleet, picker, _pending, catalog = reconcile.resolve_fleet(bundle_fleet, {}, rows, policy)
    fleet.pop("_reconcile", None)
    chosen = reconcile.gateway_settings(fleet, catalog)
    result = copy.deepcopy(template)
    result["modelPicker"] = picker
    if chosen["model"]:
        result["model"] = chosen["model"]
    if chosen["advisorModel"]:
        result["advisorModel"] = chosen["advisorModel"]
    env = result.get("env") if isinstance(result.get("env"), dict) else {}
    env.update(chosen["env"])
    result["env"] = env
    return fleet, result


def gateway_url_check(url: str) -> urllib.parse.ParseResult:
    parsed = urllib.parse.urlparse(url)
    if parsed.scheme not in {"http", "https"} or not parsed.hostname or parsed.username or parsed.password:
        fail("--gateway-url must be an http(s) URL without embedded credentials")
    if parsed.scheme == "http" and parsed.hostname.lower() not in LOOPBACK_HOSTS:
        fail("gateway URL must use HTTPS; HTTP is allowed only for loopback with --allow-insecure-http")
    return parsed


def obtain_gateway_token(args: argparse.Namespace, apply: bool) -> str | None:
    if not args.gateway_url:
        return None
    parsed = gateway_url_check(args.gateway_url)
    if parsed.scheme == "http" and not args.allow_insecure_http:
        fail("HTTP gateway URLs require explicit --allow-insecure-http")
    if args.gateway_token_env and not TOKEN_ENV_RE.fullmatch(args.gateway_token_env):
        fail(f"invalid --gateway-token-env name: {args.gateway_token_env}")
    if not apply:
        return None
    if args.gateway_token_env:
        token = os.environ.get(args.gateway_token_env)
        if not token:
            fail(f"gateway token environment variable {args.gateway_token_env} is unset; refusing to write gateway settings")
    else:
        if not sys.stdin.isatty() or not sys.stderr.isatty():
            fail("--gateway-url without --gateway-token-env requires an interactive TTY; refusing to read piped input")
        try:
            token = getpass.getpass("Gateway token (input hidden): ")
        except (EOFError, KeyboardInterrupt):
            fail("gateway token prompt cancelled; refusing to write gateway settings")
    if not token or any(ch in token for ch in "\r\n"):
        fail("gateway token is empty or contains a newline; refusing to write gateway settings")
    return token


def endpoint_key(url: object) -> str | None:
    """provider_catalog.endpoint_identity, or None for a URL it rejects."""
    try:
        return provider_catalog.endpoint_identity(url)
    except provider_catalog.CatalogError:
        return None


def same_endpoint(first: object, second: object) -> bool:
    key = endpoint_key(first)
    return key is not None and key == endpoint_key(second)


def effective_gateway(args: argparse.Namespace, existing: dict, previous: dict, gateway_token: str | None) -> tuple[str | None, str | None, bool]:
    """Return (url, token, requested): the gateway pair this install writes.

    The requested pair (--gateway-url with its token, else the live values)
    is written unless the live pair is complete and one of its values was
    changed after install, by `agentfleet use` or by hand: that change is
    authoritative, so re-running the original install command keeps the live
    pair. URL and token are decided together, so a URL is never paired with
    another gateway's token.
    """
    env = existing.get("env") if isinstance(existing.get("env"), dict) else {}
    url = args.gateway_url or env.get("ANTHROPIC_BASE_URL") or os.environ.get("ANTHROPIC_BASE_URL")
    token = gateway_token or env.get("ANTHROPIC_AUTH_TOKEN") or os.environ.get("ANTHROPIC_AUTH_TOKEN")
    url = str(url).rstrip("/") if url else None
    live_url, live_token = env.get("ANTHROPIC_BASE_URL"), env.get("ANTHROPIC_AUTH_TOKEN")
    if not (isinstance(live_url, str) and live_url and isinstance(live_token, str) and live_token):
        return url, token, True
    prior = previous_journal_map(previous)
    for key, value in (("ANTHROPIC_BASE_URL", url), ("ANTHROPIC_AUTH_TOKEN", token)):
        current = env.get(key)
        old = prior.get(f"value:env:{key}")
        owned = bool(old and old.get("installedPresent", True) and current_matches_installed(current, old))
        if current != value and not owned:
            # Verbatim: the kept values must compare equal to the live ones,
            # so none of them is rewritten or claimed as installer-owned.
            return live_url, live_token, False
    return url, token, True


def merge_settings(
    existing: dict,
    template: dict,
    home: Path,
    config_root: Path,
    args: argparse.Namespace,
    apply: bool,
    previous: dict,
    gateway_mode: bool,
    gateway_token: str | None,
    required_models: set[str],
) -> tuple[dict, list[dict], str | None, bool, list[str], list[str]]:
    desired = copy.deepcopy(existing)
    prior = previous_journal_map(previous)
    journal: dict[str, dict] = dict(prior)
    notices: list[str] = []
    redact_journal_secrets(journal)
    env_before = get_nested(existing, ["env"])
    permissions_before = get_nested(existing, ["permissions"])

    # Defaults are non-destructive. Existing singleton values survive unless a
    # prior bundle value still owns them or a direct profile must replace an
    # unusable gateway-only active model. The compaction values are refreshed
    # when this bundle still owns their previous value, so updates carry the
    # overflow fix to existing installations without overwriting user edits.
    for key, value in template.items():
        if key in {"permissions", "hooks", "env", "subagentStatusLine", "model", "modelPicker", "autoCompactWindow"}:
            continue
        identity = f"value:{key}"
        if key not in desired:
            desired[key] = copy.deepcopy(value)
            record_value_journal(journal, identity, [key], ABSENT, value, prior)
        elif identity in prior and desired[key] == prior[identity].get("installed") and desired[key] != value:
            # Refresh an unchanged value still owned by this bundle, including
            # the previous hard-limit value from the portability release, while
            # preserving a later user edit to the same setting.
            record_value_journal(journal, identity, [key], desired[key], value, prior)
            desired[key] = copy.deepcopy(value)

    # A default the bundle no longer ships is taken back if the user never
    # changed it; a value they did change is theirs from now on. Either way
    # the bundle stops owning it.
    for identity in list(journal):
        key = identity.removeprefix("value:")
        if not identity.startswith("value:") or ":" in key or key in template:
            continue
        entry = journal[identity]
        if entry.get("installedPresent") and key in desired and desired[key] == entry.get("installed"):
            if entry.get("beforePresent"):
                desired[key] = copy.deepcopy(entry.get("before"))
            else:
                del desired[key]
        del journal[identity]

    env = desired.get("env") if isinstance(desired.get("env"), dict) else {}
    env_was_absent = env_before is ABSENT
    desired["env"] = env
    template_env = template.get("env") if isinstance(template.get("env"), dict) else {}
    for key, value in template_env.items():
        # Gateway credentials, discovery, and the compaction env control are
        # handled below with profile- or pairing-specific ownership rules; a
        # plain template refresh here could desync the compaction pair.
        if key in {"ANTHROPIC_BASE_URL", "ANTHROPIC_AUTH_TOKEN", "CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY", "CLAUDE_CODE_AUTO_COMPACT_WINDOW"}:
            continue
        identity = f"value:env:{key}"
        if key not in env:
            env[key] = copy.deepcopy(value)
            record_value_journal(journal, identity, ["env", key], ABSENT, value, prior)
        elif identity in prior and env[key] == prior[identity].get("installed") and env[key] != value:
            # The same ownership rule applies to environment-backed settings.
            record_value_journal(journal, identity, ["env", key], env[key], value, prior)
            env[key] = copy.deepcopy(value)

    # Resolve the paired compaction controls after defaults are merged. The
    # pairing logic reads the merged state, not the pre-merge original, so any
    # earlier merge step that touched a compaction value is still re-paired and
    # no output can reach the write stage with a mismatched pair.
    merge_compaction_controls(desired, desired, prior, journal)
    env = desired.get("env") if isinstance(desired.get("env"), dict) else {}

    # Merge maps without clobbering user choices.
    for key in ("enabledPlugins", "extraKnownMarketplaces"):
        incoming = template.get(key)
        if not isinstance(incoming, dict):
            continue
        current = desired.get(key) if isinstance(desired.get(key), dict) else {}
        desired[key] = current
        for subkey, value in incoming.items():
            if subkey not in current:
                current[subkey] = copy.deepcopy(value)
                identity = f"value:{key}:{subkey}"
                record_value_journal(journal, identity, [key, subkey], ABSENT, value, prior)

    # Permissions are owned item-by-item, not as a singleton list.
    permission_owned: set[str] = set(previous.get("permissionOwned", [])) if isinstance(previous.get("permissionOwned"), list) else set()
    incoming_permissions = template.get("permissions") if isinstance(template.get("permissions"), dict) else {}
    permissions = desired.get("permissions") if isinstance(desired.get("permissions"), dict) else {}
    permissions_was_absent = permissions_before is ABSENT
    desired["permissions"] = permissions
    for scope in ("allow", "ask", "deny"):
        incoming = incoming_permissions.get(scope)
        if not isinstance(incoming, list):
            continue
        values = permissions.get(scope) if isinstance(permissions.get(scope), list) else []
        permissions[scope] = values
        for item in incoming:
            identity = f"list:permissions:{scope}:{permission_key(scope, item)}"
            if item not in values:
                values.append(copy.deepcopy(item))
                old = prior.get(identity)
                journal[identity] = {
                    "id": identity,
                    "kind": "list-item",
                    "path": ["permissions", scope],
                    "item": copy.deepcopy(item),
                    "beforePresent": bool(old.get("beforePresent")) if old else False,
                    "before": old.get("before") if old else None,
                    "installed": True,
                }
            permission_owned.add(permission_key(scope, item))

    # Fleet picker options are merged by model.  This keeps unrelated picker
    # rows while ensuring every installed lane can launch.
    incoming_picker = template.get("modelPicker") if isinstance(template.get("modelPicker"), dict) else {}
    old_picker = desired.get("modelPicker") if isinstance(desired.get("modelPicker"), dict) else {}
    old_options = old_picker.get("options") if isinstance(old_picker.get("options"), list) else []
    prior_owned_picker_rows = bundle_owned_picker_rows(prior, previous)
    # Preserve every existing row by default. A direct migration removes only
    # exact rows introduced by this bundle's earlier gateway profile; rows that
    # predated the bundle, including non-Claude/provider rows, remain untouched.
    new_options = [
        copy.deepcopy(item) for item in old_options
        if gateway_mode or picker_row_key(item) not in prior_owned_picker_rows
    ]
    existing_models = {item.get("model") for item in new_options if isinstance(item, dict)}
    incoming_options = incoming_picker.get("options", []) if isinstance(incoming_picker.get("options"), list) else []
    owned_picker_rows = set(prior_owned_picker_rows) if gateway_mode else set()
    for item in incoming_options:
        if not isinstance(item, dict) or item.get("model") in existing_models:
            continue
        new_options.append(copy.deepcopy(item))
        existing_models.add(item.get("model"))
        if gateway_mode:
            owned_picker_rows.add(picker_row_key(item))
    picker_value = {**old_picker, "options": new_options}
    if "replaceBuiltInOptions" in incoming_picker and "replaceBuiltInOptions" not in old_picker:
        picker_value["replaceBuiltInOptions"] = incoming_picker["replaceBuiltInOptions"]
    prior_picker = get_nested(existing, ["modelPicker"])
    required_models = set(required_models)
    picker_models = {item.get("model") for item in picker_value.get("options", []) if isinstance(item, dict)}
    picker_needs_required = not required_models.issubset(picker_models)
    if desired.get("modelPicker") != picker_value or picker_needs_required:
        identity = "value:modelPicker"
        # picker_value is derived from the freshly existing picker and removes
        # only exact bundle-owned gateway rows during a direct migration;
        # later user rows survive while required rows are ensured.
        desired["modelPicker"] = picker_value
        record_value_journal(journal, identity, ["modelPicker"], prior_picker, picker_value, prior)
    if gateway_mode:
        journal.setdefault("value:modelPicker", {
            "id": "value:modelPicker",
            "kind": "value",
            "path": ["modelPicker"],
            "beforePresent": prior_picker is not ABSENT,
            "before": copy.deepcopy(prior_picker) if prior_picker is not ABSENT else None,
            "installedPresent": True,
            "installed": copy.deepcopy(picker_value),
        })["ownedRows"] = sorted(owned_picker_rows)

    # The active model must never remain a gateway-only ID in the direct profile.
    # The first-party guarantee applies only when the installed settings carry no
    # gateway credentials; a user-configured gateway URL and token make gateway
    # model IDs and model discovery intentional rather than drift.
    gateway_ready = bool(env.get("ANTHROPIC_BASE_URL")) and bool(env.get("ANTHROPIC_AUTH_TOKEN"))
    preferred = template.get("model")
    current_model = desired.get("model", ABSENT)
    direct_invalid = not gateway_mode and not gateway_ready and current_model is not ABSENT and not is_first_party(current_model)
    old_model = prior.get("value:model")
    can_update_model = current_model is ABSENT or (old_model and current_model == old_model.get("installed")) or direct_invalid
    if can_update_model and preferred:
        if current_model != preferred:
            record_value_journal(journal, "value:model", ["model"], current_model, preferred, prior)
            desired["model"] = preferred

    # Advisor selection is also a model-bearing setting. Direct mode must not
    # retain a gateway-only advisor from the gateway template or an old install.
    preferred_advisor = template.get("advisorModel")
    current_advisor = desired.get("advisorModel", ABSENT)
    direct_advisor_invalid = not gateway_mode and not gateway_ready and current_advisor is not ABSENT and not is_first_party(current_advisor)
    old_advisor = prior.get("value:advisorModel")
    can_update_advisor = current_advisor is ABSENT or (
        old_advisor and current_advisor == old_advisor.get("installed")
    ) or direct_advisor_invalid
    if can_update_advisor and preferred_advisor:
        if current_advisor != preferred_advisor:
            record_value_journal(journal, "value:advisorModel", ["advisorModel"], current_advisor, preferred_advisor, prior)
            desired["advisorModel"] = preferred_advisor

    # Platform-safe hook merge at inner-command granularity. Discovery is an
    # explicit opt-in, but a previously enabled value backed by gateway
    # credentials is preserved across updates in either profile, whether this
    # bundle installed it or the user set it directly; a fresh install still
    # defaults to disabled.
    discovery_enabled = (
        gateway_mode
        and (
            args.enable_model_discovery
            or (
                # Any earlier install: a native install may have switched to
                # a gateway with agentfleet since.
                bool(previous)
                and env.get("CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY") == "1"
            )
        )
        or (
            not gateway_mode
            and gateway_ready
            and env.get("CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY") == "1"
        )
    )
    discovery_identity = "value:env:CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY"
    discovery_value = "1" if discovery_enabled else "0"
    discovery_current = env.get("CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY", ABSENT)
    if discovery_current != discovery_value:
        record_value_journal(
            journal,
            discovery_identity,
            ["env", "CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY"],
            discovery_current,
            discovery_value,
            prior,
        )
        env["CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY"] = discovery_value
    template_with_hooks = platform_hook_template(home, config_root, template, discovery_enabled)
    incoming_hooks = template_with_hooks.get("hooks") if isinstance(template_with_hooks.get("hooks"), dict) else {}
    existing_hooks = desired.get("hooks") if isinstance(desired.get("hooks"), dict) else {}
    desired["hooks"] = clean_hook_groups(existing_hooks, incoming_hooks, journal, prior, notices)

    status = template_with_hooks.get("subagentStatusLine")
    if isinstance(status, dict):
        current_status = desired.get("subagentStatusLine", ABSENT)
        identity = "value:subagentStatusLine"
        old = prior.get(identity)
        if current_status is ABSENT or (old and current_status == old.get("installed")) or is_owned_command(current_status):
            desired["subagentStatusLine"] = copy.deepcopy(status)
            record_value_journal(journal, identity, ["subagentStatusLine"], current_status, status, prior)

    gateway_owned = False
    gateway_state = None
    if gateway_mode:
        url, token, requested = effective_gateway(args, existing, previous, gateway_token)
        if not url or not token:
            fail("gateway mode requires both URL and token before any write")
        gateway_url_check(str(url))
        if urllib.parse.urlparse(str(url)).scheme == "http" and not args.allow_insecure_http and args.gateway_url and requested:
            fail("HTTP gateway URLs require explicit --allow-insecure-http")
        for key, value in (("ANTHROPIC_BASE_URL", str(url)), ("ANTHROPIC_AUTH_TOKEN", str(token))):
            identity = f"value:env:{key}"
            current = env.get(key, ABSENT)
            old = prior.get(identity)
            # A gateway credential remains setup-owned only while its current
            # value equals the prior installed value. A user replacement is
            # carried forward but must not become uninstall-owned.
            owned = bool(old and old.get("installedPresent", True) and current_matches_installed(current, old))
            if current != value and requested:
                # effective_gateway keeps a live pair changed after install, so
                # a differing value here is one this install may write.
                record_value_journal(journal, identity, ["env", key], current, value, prior)
                env[key] = value
            elif owned:
                journal[identity] = copy.deepcopy(old)
                journal[identity]["installedPresent"] = True
                journal[identity]["installed"] = secret_digest(value) if identity in SECRET_JOURNAL_IDS else value
            elif current is not ABSENT:
                # Explicit gateway credentials supplied for a user-edited
                # existing value are functional, but not owned for uninstall.
                journal.pop(identity, None)
            gateway_owned = gateway_owned or bool(journal.get(identity))
        # Claude Code sends ANTHROPIC_API_KEY in preference to the gateway
        # token, so a key exported in the shell would bypass the gateway. An
        # empty value in settings masks it. The empty value is only ever
        # written by AgentFleet, so an unjournaled one is claimed as well; a
        # real key in settings is the user's and stays.
        identity = API_KEY_JOURNAL_ID
        current = env.get("ANTHROPIC_API_KEY", ABSENT)
        if current is ABSENT or (current == "" and identity not in prior):
            record_value_journal(journal, identity, ["env", "ANTHROPIC_API_KEY"], ABSENT, "", prior)
            env["ANTHROPIC_API_KEY"] = ""
        elif current != "":
            journal.pop(identity, None)
            print("claude-agents-config: settings.json sets ANTHROPIC_API_KEY; Claude Code may send it to the gateway instead of the gateway token; remove it unless the gateway expects it.", file=sys.stderr)
    else:
        # Only remove credentials previously owned by this bundle.  A user's
        # existing gateway environment remains untouched, but the installed fleet
        # profile is direct Anthropic and discovery is disabled.
        # Discovery has already been journaled above with the disabled value.
        for key in ("ANTHROPIC_BASE_URL", "ANTHROPIC_AUTH_TOKEN", "ANTHROPIC_API_KEY"):
            identity = f"value:env:{key}"
            old = prior.get(identity)
            # The empty API key masks a shell key only while a gateway is
            # configured; it stays while a user-owned gateway URL does.
            if key == "ANTHROPIC_API_KEY" and "ANTHROPIC_BASE_URL" in env:
                continue
            if old and current_matches_installed(env.get(key, ABSENT), old):
                # Carry the original pre-gateway value into the new direct
                # profile so a later uninstall restores user settings rather
                # than restoring the removed gateway credential.
                journal[identity] = copy.deepcopy(old)
                journal[identity]["installedPresent"] = False
                journal[identity]["installed"] = None
                env.pop(key, None)

    # Record container ownership after all merges. This lets uninstall remove
    # an installer-created empty env/permissions map while preserving a map that
    # existed before or was subsequently edited.
    if env_was_absent:
        journal["value:env"] = {
            "id": "value:env", "kind": "value", "path": ["env"],
            "beforePresent": False, "before": None, "installedPresent": True,
            "installed": {key: secret_digest(value) if key == "ANTHROPIC_AUTH_TOKEN" else copy.deepcopy(value) for key, value in env.items()},
        }
    if permissions_was_absent:
        journal["value:permissions"] = {
            "id": "value:permissions", "kind": "value", "path": ["permissions"],
            "beforePresent": False, "before": None, "installedPresent": True, "installed": copy.deepcopy(permissions),
        }
    # Keep only useful journal entries and return stable order.
    journal_list = sorted(journal.values(), key=lambda item: item.get("id", ""))
    return desired, journal_list, gateway_state, gateway_owned, sorted(permission_owned), notices


