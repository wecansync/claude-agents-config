def existing_fleet_map(home: Path, config_root: Path) -> dict:
    """The installed fleet map, newest of the two mirrors, or {}."""
    candidates = [home / ".claude" / "fleet.json", config_root / "delegate-skills" / "config.json"]
    present = [path for path in candidates if path.is_file()]
    present.sort(key=lambda path: path.stat().st_mtime, reverse=True)
    for path in present:
        try:
            value = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            continue
        if isinstance(value, dict) and isinstance(value.get("lanes"), dict):
            return value
    return {}


