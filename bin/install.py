def is_owned_command(item: object) -> bool:
    text = command_text(item)
    if MARKER in text:
        return True
    return any(fragment in text for fragment in LEGACY_FRAGMENT_KIND)


def merge_unique(left: object, right: object) -> list:
    old = left if isinstance(left, list) else []
    incoming = right if isinstance(right, list) else []
    result = []
    seen = set()
    for item in [*old, *incoming]:
        key = json.dumps(item, ensure_ascii=False, sort_keys=True)
        if key not in seen:
            seen.add(key)
            result.append(copy.deepcopy(item))
    return result


