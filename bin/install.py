def resolve_dir(value: str | Path | None) -> Path:
    raw = str(value) if value is not None else ""
    path = Path(raw).expanduser() if raw else Path.cwd()
    if not path.is_absolute():
        path = Path.cwd() / path
    return path.resolve(strict=False)


