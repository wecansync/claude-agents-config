#!/usr/bin/env python3
"""Install, update, roll back, and uninstall the portable Claude fleet bundle."""
from __future__ import annotations

import argparse
import copy
import datetime as dt
import getpass
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys
import tempfile
import urllib.parse

MARKER = "claude-agents-config:"
GENERATED_MARKER = "GENERATED BY claude-fleet-sync"
TOKEN_ENV_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def fail(message: str, code: int = 1) -> None:
    print(f"claude-agents-config: {message}", file=sys.stderr)
    raise SystemExit(code)


def resolve_dir(value: str | None) -> Path:
    raw = value or ""
    path = Path(raw).expanduser() if raw else Path.cwd()
    if not path.is_absolute():
        path = Path.cwd() / path
    return path.resolve(strict=False)


def load_json(path: Path, label: str) -> dict:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"{label} not found: {path}")
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot read valid JSON from {label} ({path}): {exc}")
    if not isinstance(value, dict):
        fail(f"{label} must contain a JSON object: {path}")
    return value


def lexists(path: Path) -> bool:
    return os.path.lexists(path)


def read_bytes(path: Path) -> bytes:
    try:
        return path.read_bytes()
    except OSError as exc:
        fail(f"cannot read {path}: {exc}")


def source_bytes(bundle: Path, rel: str) -> bytes:
    path = bundle / rel
    if not path.is_file():
        fail(f"bundle is incomplete; missing {path}")
    return read_bytes(path)


def text_with_marker(bundle: Path, rel: str) -> bytes:
    return source_bytes(bundle, rel)


def target_home(args: argparse.Namespace) -> Path:
    if args.home:
        return resolve_dir(args.home)
    if args.prefix:
        # A prefix without --home is a complete portable sandbox root.
        return resolve_dir(args.prefix)
    env_home = os.environ.get("HOME")
    if not env_home:
        fail("HOME is unset; pass --home DIR or --prefix DIR")
    return resolve_dir(env_home)


def target_bin(args: argparse.Namespace, home: Path) -> Path:
    if args.prefix:
        return resolve_dir(args.prefix) / "bin"
    return home / ".local" / "bin"


def normalize_hooks(value: object, home: Path) -> object:
    if isinstance(value, str):
        return value.replace("__CLAUDE_HOME__", str(home / ".claude"))
    if isinstance(value, list):
        return [normalize_hooks(item, home) for item in value]
    if isinstance(value, dict):
        return {key: normalize_hooks(item, home) for key, item in value.items()}
    return value


def command_text(item: object) -> str:
    if not isinstance(item, dict):
        return ""
    hooks = item.get("hooks")
    if not isinstance(hooks, list):
        return ""
    return " ".join(str(h.get("command", "")) for h in hooks if isinstance(h, dict))


def is_owned_hook(item: object) -> bool:
    text = command_text(item)
    if MARKER in text:
        return True
    # Migrate the unmarked live-source hooks once, but do not remove an arbitrary
    # user hook merely because it mentions a similarly named command.
    legacy_paths = (
        "/.claude/route-to-fleet.py",
        "/.claude/subagent-statusline.py",
        "/.claude/sync-omniroute-models.mjs",
        "/.local/bin/agent-brain hook ",
    )
    return any(path in text for path in legacy_paths)


def merge_unique(left: object, right: object) -> object:
    if not isinstance(left, list):
        left = []
    if not isinstance(right, list):
        right = []
    result = []
    seen = set()
    for item in [*left, *right]:
        key = json.dumps(item, ensure_ascii=False, sort_keys=True)
        if key not in seen:
            seen.add(key)
            result.append(item)
    return result


def permission_key(scope: str, value: object) -> str:
    return json.dumps([scope, value], ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def merge_settings(
    existing: dict,
    template: dict,
    home: Path,
    args: argparse.Namespace,
    apply: bool,
    previous_permission_owned: list[str] | None = None,
) -> tuple[dict, bool, str | None, list[str]]:
    desired = copy.deepcopy(existing)
    permission_owned = set(previous_permission_owned or [])
    for key, value in template.items():
        if key == "permissions":
            current = desired.get(key) if isinstance(desired.get(key), dict) else {}
            incoming = value if isinstance(value, dict) else {}
            merged = copy.deepcopy(current)
            for subkey in ("allow", "ask", "deny"):
                if subkey in incoming:
                    current_values = current.get(subkey) if isinstance(current.get(subkey), list) else []
                    merged[subkey] = merge_unique(current_values, incoming[subkey])
                    for item in incoming[subkey] if isinstance(incoming[subkey], list) else []:
                        if item not in current_values:
                            permission_owned.add(permission_key(subkey, item))
            desired[key] = merged
        elif key == "hooks":
            current = desired.get(key) if isinstance(desired.get(key), dict) else {}
            incoming = normalize_hooks(value, home)
            merged = copy.deepcopy(current)
            for event, entries in incoming.items():
                old_entries = current.get(event) if isinstance(current.get(event), list) else []
                keep = [entry for entry in old_entries if not is_owned_hook(entry)]
                merged[event] = merge_unique(keep, entries)
            desired[key] = merged
        elif key == "enabledPlugins" or key == "extraKnownMarketplaces":
            current = desired.get(key) if isinstance(desired.get(key), dict) else {}
            merged = copy.deepcopy(current)
            if isinstance(value, dict):
                merged.update(copy.deepcopy(value))
            desired[key] = merged
        elif key == "env":
            current = desired.get(key) if isinstance(desired.get(key), dict) else {}
            merged = copy.deepcopy(current)
            if isinstance(value, dict):
                merged.update(copy.deepcopy(value))
            desired[key] = merged
        elif key == "subagentStatusLine":
            desired[key] = normalize_hooks(value, home)
        else:
            desired[key] = copy.deepcopy(value)

    env = desired.setdefault("env", {})
    if not isinstance(env, dict):
        fail("settings.env must be an object")
    # A template never carries credentials. If an existing configuration has a
    # token but no URL, preserve it as an unrelated value but do not enable it.
    gateway_url = args.gateway_url
    gateway_token = None
    gateway_state = None
    if args.gateway_token_env and not gateway_url:
        fail("--gateway-token-env requires --gateway-url; refusing to enable an incomplete gateway")
    if gateway_url is not None:
        parsed = urllib.parse.urlparse(gateway_url)
        if parsed.scheme not in {"http", "https"} or not parsed.netloc or parsed.username or parsed.password:
            fail("--gateway-url must be an http(s) URL without embedded credentials")
        if apply:
            env_name = args.gateway_token_env
            if env_name and not TOKEN_ENV_RE.fullmatch(env_name):
                fail(f"invalid --gateway-token-env name: {env_name}")
            if env_name:
                gateway_token = os.environ.get(env_name)
                if not gateway_token and not sys.stdin.isatty():
                    fail(f"gateway token environment variable {env_name} is unset; refusing to write gateway settings")
            if not gateway_token:
                try:
                    gateway_token = getpass.getpass("Gateway token (input hidden): ")
                except (EOFError, KeyboardInterrupt):
                    fail("gateway token prompt cancelled; refusing to write gateway settings")
            if not gateway_token or any(ch in gateway_token for ch in "\r\n"):
                fail("gateway token is empty or contains a newline; refusing to write gateway settings")
            env["ANTHROPIC_BASE_URL"] = gateway_url.rstrip("/")
            env["ANTHROPIC_AUTH_TOKEN"] = gateway_token
            gateway_state = "configured"
        else:
            gateway_state = "would-configure"
    elif env.get("ANTHROPIC_BASE_URL") and not env.get("ANTHROPIC_AUTH_TOKEN"):
        # An old half-configured gateway is setup-owned and unsafe. Remove only its URL;
        # unrelated environment values remain untouched.
        env.pop("ANTHROPIC_BASE_URL", None)
        gateway_state = "disabled-incomplete-existing"
    return desired, bool(gateway_state == "configured"), gateway_state, sorted(permission_owned)


def metadata_for(
    home: Path,
    bin_dir: Path,
    version: str,
    managed: list[tuple[str, Path]],
    gateway_owned: bool,
    permission_owned: list[str],
) -> bytes:
    body = {
        "marker": MARKER,
        "version": version,
        "managed": [{"id": ident, "path": str(path)} for ident, path in sorted(managed)],
        "gatewayKeysOwned": gateway_owned,
        "permissionOwned": permission_owned,
    }
    return (json.dumps(body, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def managed_specs(
    bundle: Path,
    home: Path,
    bin_dir: Path,
    settings_bytes: bytes,
    version: str,
    gateway_owned: bool,
    permission_owned: list[str],
) -> tuple[dict[Path, tuple[bytes, int, str]], Path]:
    claude = home / ".claude"
    fleet = home / ".config" / "delegate-skills"
    specs: dict[Path, tuple[bytes, int, str]] = {}
    def add(path: Path, data: bytes, mode: int, ident: str) -> None:
        specs[path] = (data, mode, ident)
    add(claude / "settings.json", settings_bytes, 0o600, "home:.claude/settings.json")
    add(claude / "CLAUDE.md", source_bytes(bundle, "config/CLAUDE.md"), 0o644, "home:.claude/CLAUDE.md")
    add(claude / "route-to-fleet.py", source_bytes(bundle, "scripts/route-to-fleet.py"), 0o755, "home:.claude/route-to-fleet.py")
    add(claude / "subagent-statusline.py", source_bytes(bundle, "scripts/subagent-statusline.py"), 0o755, "home:.claude/subagent-statusline.py")
    add(claude / "sync-omniroute-models.mjs", source_bytes(bundle, "scripts/sync-omniroute-models.mjs"), 0o755, "home:.claude/sync-omniroute-models.mjs")
    add(fleet / "config.json", source_bytes(bundle, "config/delegate-fleet.json"), 0o644, "home:.config/delegate-skills/config.json")
    add(fleet / "generate-claude-agents.mjs", source_bytes(bundle, "scripts/generate-claude-agents.mjs"), 0o755, "home:.config/delegate-skills/generate-claude-agents.mjs")
    for agent in sorted((bundle / "agents").glob("fleet-*.md")):
        add(claude / "agents" / agent.name, agent.read_bytes(), 0o644, f"home:.claude/agents/{agent.name}")
    add(bin_dir / "claude-fleet-sync", source_bytes(bundle, "bin/claude-fleet-sync"), 0o755, f"prefix:{bin_dir.name}/claude-fleet-sync")
    doctor_rel = "bin/claude-agents-doctor"
    add(bin_dir / "claude-agents-doctor", source_bytes(bundle, doctor_rel), 0o755, f"prefix:{bin_dir.name}/claude-agents-doctor")
    metadata_path = claude / ".claude-agents-config-install.json"
    managed_for_meta = [(ident, path) for path, (_, _, ident) in specs.items()]
    add(
        metadata_path,
        metadata_for(home, bin_dir, version, managed_for_meta, gateway_owned, permission_owned),
        0o600,
        "home:.claude/.claude-agents-config-install.json",
    )
    return specs, metadata_path


def old_metadata(home: Path) -> dict:
    path = home / ".claude" / ".claude-agents-config-install.json"
    if not path.is_file():
        return {}
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        return value if isinstance(value, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def metadata_owns(meta: dict, path: Path) -> bool:
    for item in meta.get("managed", []) if isinstance(meta.get("managed"), list) else []:
        if isinstance(item, dict) and item.get("path") == str(path):
            return True
    return False


def owned_existing(path: Path, data: bytes, meta: dict, bundle: Path, specs: dict[Path, tuple[bytes, int, str]]) -> bool:
    if metadata_owns(meta, path) or MARKER.encode() in data or GENERATED_MARKER.encode() in data:
        return True
    if path.name == "settings.json":
        return True
    if path.name == "config.json" and path.parent.name == "delegate-skills":
        try:
            return json.loads(data) == json.loads(source_bytes(bundle, "config/delegate-fleet.json"))
        except (ValueError, json.JSONDecodeError):
            return False
    expected = specs.get(path)
    return bool(expected and expected[0] == data)


def check_parent_conflicts(specs: dict[Path, tuple[bytes, int, str]], meta: dict, bundle: Path, force: bool) -> list[Path]:
    conflicts = []
    for path, (data, _, _) in specs.items():
        if not lexists(path) or path.is_dir():
            if path.is_dir():
                conflicts.append(path)
            continue
        if path.is_symlink():
            conflicts.append(path)
            continue
        if not owned_existing(path, read_bytes(path), meta, bundle, specs) and not force:
            conflicts.append(path)
    return conflicts


def backup_existing(specs: dict[Path, tuple[bytes, int, str]], home: Path, dry: bool) -> Path | None:
    existing = [path for path in specs if lexists(path) and not path.is_dir()]
    if not existing:
        return None
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S")
    backup_root = home / ".claude" / "backups" / "claude-agents-config"
    root = backup_root / (stamp + "Z")
    if not dry:
        suffix = 0
        while root.exists():
            suffix += 1
            root = backup_root / f"{stamp}Z-{suffix}"
    if dry:
        return root
    root.mkdir(parents=True, exist_ok=False)
    records = []
    for index, path in enumerate(sorted(existing, key=str)):
        backup_file = root / "files" / f"{index:03d}.bin"
        backup_file.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, backup_file, follow_symlinks=False)
        mode = stat.S_IMODE(path.stat().st_mode)
        records.append({"path": str(path), "backup": str(backup_file.relative_to(root)), "mode": mode, "existed": True})
    (root / "backup.json").write_text(json.dumps({"marker": MARKER, "records": records}, indent=2) + "\n", encoding="utf-8")
    os.chmod(root / "backup.json", 0o600)
    for directory in (root, root / "files"):
        os.chmod(directory, 0o700)
    return root


def atomic_write(path: Path, data: bytes, mode: int) -> None:
    if path.parent.exists() and not path.parent.is_dir():
        fail(f"cannot create parent directory because it is a file: {path.parent}")
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    temp = Path(temp_name)
    try:
        os.write(fd, data)
        os.fchmod(fd, mode)
        os.close(fd)
        os.replace(temp, path)
        os.chmod(path, mode)
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            temp.unlink()
        except OSError:
            pass
        raise


def print_plan(specs: dict[Path, tuple[bytes, int, str]], backup: Path | None, conflicts: list[Path], gateway_state: str | None, dry: bool) -> None:
    print("Mode: dry-run" if dry else "Mode: apply")
    print("Gateway: " + (gateway_state or "not changed; no gateway arguments supplied"))
    if backup:
        print(f"Backup snapshot: {backup}")
    for path, (data, _, _) in sorted(specs.items(), key=lambda item: str(item[0])):
        state = "create" if not lexists(path) else ("update" if path.read_bytes() != data else "unchanged")
        print(f"  {state}: {path}")
    if conflicts:
        print("Conflicts requiring --force-owned:", file=sys.stderr)
        for path in conflicts:
            print(f"  {path}", file=sys.stderr)


def run_doctor(bundle: Path, home: Path, bin_dir: Path) -> int:
    doctor = bundle / "bin" / "claude-agents-doctor"
    command = [sys.executable, str(doctor), "--check", "--home", str(home), "--prefix", str(bin_dir.parent), "--bundle", str(bundle)]
    result = subprocess.run(command, text=True)
    return result.returncode


def apply_install(args: argparse.Namespace, bundle: Path, dry: bool) -> int:
    home = target_home(args)
    bin_dir = target_bin(args, home)
    version = (bundle / "VERSION").read_text(encoding="utf-8").strip()
    template = load_json(bundle / "config/settings.template.json", "settings template")
    settings_path = home / ".claude" / "settings.json"
    existing = load_json(settings_path, "existing settings") if settings_path.is_file() else {}
    previous = old_metadata(home)
    desired, gateway_owned, gateway_state, permission_owned = merge_settings(
        existing,
        template,
        home,
        args,
        apply=not dry,
        previous_permission_owned=previous.get("permissionOwned") if isinstance(previous.get("permissionOwned"), list) else None,
    )
    settings_bytes = (json.dumps(desired, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    specs, metadata_path = managed_specs(bundle, home, bin_dir, settings_bytes, version, gateway_owned, permission_owned)
    meta = old_metadata(home)
    conflicts = check_parent_conflicts(specs, meta, bundle, args.force_owned)
    backup = backup_existing(specs, home, dry=False) if not dry and not conflicts else (backup_existing(specs, home, dry=True) if dry and not conflicts else None)
    print_plan(specs, backup, conflicts, gateway_state, dry)
    if conflicts:
        return 1
    if dry:
        return 0
    if backup:
        print(f"Created backup snapshot: {backup}")
    for path, (data, mode, _) in specs.items():
        if lexists(path) and path.is_dir():
            fail(f"refusing to replace directory: {path}")
        if not lexists(path) or read_bytes(path) != data or stat.S_IMODE(path.stat().st_mode) != mode:
            atomic_write(path, data, mode)
    print(f"Installed Claude fleet bundle {version} under {home}")
    return run_doctor(bundle, home, bin_dir)


def settings_for_uninstall(path: Path, template: dict, home: Path, meta: dict) -> tuple[bytes | None, bool]:
    if not path.is_file():
        return None, False
    current = load_json(path, "installed settings")
    changed = False
    hooks = current.get("hooks")
    if isinstance(hooks, dict):
        for event in list(hooks):
            entries = hooks[event]
            if isinstance(entries, list):
                kept = [entry for entry in entries if not is_owned_hook(entry)]
                if kept != entries:
                    changed = True
                    if kept:
                        hooks[event] = kept
                    else:
                        del hooks[event]
    status = current.get("subagentStatusLine")
    if isinstance(status, dict) and MARKER in str(status.get("command", "")):
        current.pop("subagentStatusLine", None)
        changed = True
    permissions = current.get("permissions")
    template_permissions = template.get("permissions") if isinstance(template, dict) else {}
    owned_permissions = {
        item for item in meta.get("permissionOwned", [])
        if isinstance(item, str)
    }
    if isinstance(permissions, dict) and isinstance(template_permissions, dict):
        for subkey in ("allow", "ask", "deny"):
            values = permissions.get(subkey)
            remove = {key for key in owned_permissions if key.startswith(f'[{json.dumps(subkey)},')}
            if isinstance(values, list):
                kept = [item for item in values if json.dumps([subkey, item], ensure_ascii=False, sort_keys=True, separators=(",", ":")) not in remove]
                if kept != values:
                    permissions[subkey] = kept
                    changed = True
    if meta.get("gatewayKeysOwned"):
        env = current.get("env")
        if isinstance(env, dict):
            for key in ("ANTHROPIC_BASE_URL", "ANTHROPIC_AUTH_TOKEN"):
                if key in env:
                    env.pop(key, None)
                    changed = True
    if not changed:
        return path.read_bytes(), False
    return (json.dumps(current, ensure_ascii=False, indent=2) + "\n").encode("utf-8"), True


def uninstall(args: argparse.Namespace, bundle: Path, dry: bool) -> int:
    home = target_home(args)
    bin_dir = target_bin(args, home)
    meta = old_metadata(home)
    template = load_json(bundle / "config/settings.template.json", "settings template")
    settings_path = home / ".claude" / "settings.json"
    new_settings, settings_changed = settings_for_uninstall(settings_path, template, home, meta)
    candidates = []
    managed = meta.get("managed", []) if isinstance(meta.get("managed"), list) else []
    for item in managed:
        if isinstance(item, dict) and isinstance(item.get("path"), str):
            candidates.append(Path(item["path"]))
    if not candidates:
        candidates = [
            home / ".claude" / "CLAUDE.md", home / ".claude" / "route-to-fleet.py",
            home / ".claude" / "subagent-statusline.py", home / ".claude" / "sync-omniroute-models.mjs",
            home / ".config" / "delegate-skills" / "config.json", home / ".config" / "delegate-skills" / "generate-claude-agents.mjs",
            bin_dir / "claude-fleet-sync", bin_dir / "claude-agents-doctor",
        ]
        candidates += sorted((home / ".claude" / "agents").glob("fleet-*.md")) if (home / ".claude" / "agents").is_dir() else []
    candidates = [path for path in candidates if path != settings_path and path.name != ".claude-agents-config-install.json"]
    removable = []
    for path in candidates:
        if not lexists(path) or path.is_dir():
            continue
        data = read_bytes(path)
        if metadata_owns(meta, path) or MARKER.encode() in data or GENERATED_MARKER.encode() in data:
            removable.append(path)
    if settings_changed:
        removable.append(settings_path)
    backup_specs = {path: (read_bytes(path), stat.S_IMODE(path.stat().st_mode), "uninstall") for path in removable if lexists(path)}
    backup = backup_existing(backup_specs, home, dry=False) if not dry else backup_existing(backup_specs, home, dry=True)
    print("Mode: dry-run" if dry else "Mode: apply")
    if backup:
        print(f"Backup snapshot: {backup}")
    for path in sorted(removable, key=str):
        if path == settings_path:
            print(f"  update settings: {path}")
        else:
            print(f"  remove: {path}")
    if dry:
        return 0
    for path in removable:
        if path == settings_path:
            atomic_write(path, new_settings or b"{}\n", 0o600)
        else:
            try:
                path.unlink()
            except FileNotFoundError:
                pass
    metadata_path = home / ".claude" / ".claude-agents-config-install.json"
    if metadata_path.exists():
        metadata_path.unlink()
    print(f"Removed setup-owned Claude fleet files under {home}; unrelated settings remain.")
    return 0


def find_latest_backup(home: Path) -> Path:
    root = home / ".claude" / "backups" / "claude-agents-config"
    candidates = [p for p in root.iterdir() if p.is_dir() and (p / "backup.json").is_file()] if root.is_dir() else []
    if not candidates:
        fail(f"no Claude fleet backup found under {root}")
    return sorted(candidates, key=lambda p: p.name)[-1]


def rollback(args: argparse.Namespace, home: Path, dry: bool) -> int:
    backup = resolve_dir(args.backup) if args.backup else find_latest_backup(home)
    if not backup.is_dir():
        fail(f"backup directory not found: {backup}")
    manifest = load_json(backup / "backup.json", "backup manifest")
    records = manifest.get("records")
    if not isinstance(records, list):
        fail(f"backup manifest has no records: {backup / 'backup.json'}")
    print("Mode: dry-run" if dry else "Mode: apply")
    print(f"Rollback source: {backup}")
    for record in records:
        if not isinstance(record, dict):
            continue
        path = Path(record.get("path", ""))
        print(f"  restore: {path}")
    if dry:
        return 0
    for record in records:
        if not isinstance(record, dict):
            continue
        path = Path(record.get("path", ""))
        backup_file = backup / str(record.get("backup", ""))
        if not backup_file.is_file():
            fail(f"backup payload missing: {backup_file}")
        atomic_write(path, backup_file.read_bytes(), int(record.get("mode", 0o600)))
    print("Rollback restored the selected backup snapshot.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Portable Claude Code fleet bundle installer")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="apply the installation or selected operation")
    mode.add_argument("--dry-run", action="store_true", help="show changes without writing")
    mode.add_argument("--check", action="store_true", help="run the bundle doctor")
    operation = parser.add_mutually_exclusive_group()
    operation.add_argument("--uninstall", action="store_true", help="remove setup-owned files; combine with --apply or --dry-run")
    operation.add_argument("--rollback", action="store_true", help="restore the latest or --backup snapshot; combine with --apply or --dry-run")
    parser.add_argument("--home", help="target home containing .claude and .config")
    parser.add_argument("--prefix", help="target prefix; without --home it is also the sandbox home")
    parser.add_argument("--gateway-url", help="gateway http(s) URL; only applied with a token")
    parser.add_argument("--gateway-token-env", help="environment variable containing the gateway token")
    parser.add_argument("--backup", help="backup directory for --rollback")
    parser.add_argument("--force-owned", action="store_true", help="replace conflicting unmarked managed files after backup")
    parser.add_argument("--bundle", required=True, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if not any((args.apply, args.dry_run, args.check, args.uninstall, args.rollback)):
        parser.error("choose an action explicitly: --dry-run, --apply, --check, --uninstall, or --rollback")
    if args.uninstall and (args.gateway_url or args.gateway_token_env):
        parser.error("gateway options do not apply to --uninstall")
    bundle = resolve_dir(args.bundle)
    if not (bundle / "VERSION").is_file() or not (bundle / "manifest.json").is_file():
        fail(f"bundle is incomplete at {bundle}; VERSION and manifest.json are required")
    home = target_home(args)
    if args.check:
        doctor = bundle / "bin" / "claude-agents-doctor"
        return subprocess.run([sys.executable, str(doctor), "--check", "--home", str(home), "--prefix", str(target_bin(args, home).parent), "--bundle", str(bundle)]).returncode
    if args.rollback:
        if not args.apply and not args.dry_run:
            parser.error("--rollback requires explicit --apply or --dry-run")
        return rollback(args, home, dry=args.dry_run)
    if args.uninstall:
        if not args.apply and not args.dry_run:
            parser.error("--uninstall requires explicit --apply or --dry-run")
        return uninstall(args, bundle, dry=args.dry_run)
    return apply_install(args, bundle, dry=args.dry_run)

if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BrokenPipeError:
        raise SystemExit(1)
