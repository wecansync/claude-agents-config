def profile_data(
    bundle: Path,
    gateway_mode: bool,
    *,
    home: Path,
    config_root: Path,
    existing: dict,
    gateway_url: str | None,
    gateway_token: str | None,
    policy: dict,
    tier_labels: dict[str, str] | None = None,
    drop_shipped_pins: bool = False,
    carry_from: dict | None = None,
) -> tuple[str, bytes, dict, dict, str]:
    """Return (profile, fleet bytes, fleet, settings template, catalog note).

    Lane choices are carried from carry_from, else the installed fleet.
    """
    template = load_json(bundle / "config/settings.template.json", "settings template")
    fleet_source = load_json(bundle / "config/delegate-fleet.json", "fleet configuration")
    fleet_source.setdefault("integrations", {})["agentBrain"] = optional_agent_brain_available()
    note = ""
    installed = carry_from if carry_from is not None else existing_fleet_map(home, config_root)
    if gateway_mode:
        profile = "gateway"
        carried = carry_lane_choices(fleet_source, installed, drop_shipped_pins=drop_shipped_pins)
        if tier_labels:
            carried["modelTiers"] = {**carried.get("modelTiers", {}), **tier_labels}
        url = gateway_url or (existing.get("env") or {}).get("ANTHROPIC_BASE_URL")
        # The caller withholds a token that belongs to another endpoint.
        token = gateway_token if gateway_url else (existing.get("env") or {}).get("ANTHROPIC_AUTH_TOKEN")
        rows, source = discover_gateway_rows(home, url, token, existing)
        if rows:
            fleet, template_profile = gateway_profile(carried, template, rows, policy)
            note = f"gateway models: {len(rows)} ({source})"
        else:
            # Unreachable gateway on a fresh install: fall back to Claude
            # Code's aliases, which the gateway serves through the
            # ANTHROPIC_DEFAULT_*_MODEL mapping; the startup reconcile hook
            # replaces them with discovered models once the gateway answers.
            fleet = direct_fleet(carried)
            # Keep the user's preferences so the startup reconcile can restore
            # them once the gateway answers again.
            for name, config in carried.get("lanes", {}).items():
                if isinstance(config, dict) and config.get("preferred") and isinstance(fleet["lanes"].get(name), dict):
                    fleet["lanes"][name]["preferred"] = copy.deepcopy(config["preferred"])
            template_profile = copy.deepcopy(template)
            template_profile["modelPicker"] = {"options": copy.deepcopy(NATIVE_PICKER), "replaceBuiltInOptions": True}
            template_profile["model"] = "default"
            template_profile["advisorModel"] = "opus"
            note = "gateway models: unavailable (using Claude aliases until the gateway answers)"
    else:
        # Custom lanes carry over here too; direct_fleet then maps every lane,
        # custom ones included, to the native alias for its tier.
        fleet = direct_fleet(carry_lane_choices(fleet_source, installed, drop_shipped_pins=drop_shipped_pins))
        template_profile = direct_template(template)
        profile = "direct-anthropic"
    fleet_bytes = json_bytes(fleet)
    return profile, fleet_bytes, fleet, template_profile, note


def determine_gateway(args: argparse.Namespace, previous: dict, existing: dict, apply: bool, switched_to_native: bool = False) -> tuple[bool, str | None]:
    existing_env = existing.get("env") if isinstance(existing.get("env"), dict) else {}
    direct_requested = getattr(args, "provider", None) in {"native", "anthropic-api"}
    if direct_requested and (existing_env.get("ANTHROPIC_BASE_URL") or existing_env.get("ANTHROPIC_AUTH_TOKEN")):
        fail("this home is configured for a gateway; update without --provider first, then switch to your Claude login with: agentfleet use native")
    if args.gateway_token_env and not args.gateway_url:
        fail("--gateway-token-env requires --gateway-url")
    if args.gateway_url:
        gateway_url_check(args.gateway_url)
        if urllib.parse.urlparse(args.gateway_url).scheme == "http" and not args.allow_insecure_http:
            fail("HTTP gateway URLs require explicit --allow-insecure-http")
        return True, "gateway (explicit URL and token)" if apply else "gateway (would configure with URL and token)"
    env = existing.get("env") if isinstance(existing.get("env"), dict) else {}
    existing_url = env.get("ANTHROPIC_BASE_URL")
    existing_token = env.get("ANTHROPIC_AUTH_TOKEN")
    if existing_url or existing_token:
        if not (isinstance(existing_url, str) and existing_url and isinstance(existing_token, str) and existing_token):
            fail("existing gateway settings are incomplete; provide --gateway-url and --gateway-token-env")
        gateway_url_check(existing_url)
        # Credentials already present in settings are an intentional gateway
        # profile even when older metadata did not record gateway ownership.
        return True, "gateway (existing URL and token)"
    # An explicit direct provider wins over credentials exported in the shell:
    # they must never be copied into settings.json against the user's choice.
    if direct_requested:
        return False, "direct Anthropic (requested)"
    env_url = os.environ.get("ANTHROPIC_BASE_URL")
    env_token = os.environ.get("ANTHROPIC_AUTH_TOKEN")
    if env_url and env_token:
        gateway_url_check(env_url)
        return True, "gateway (detected from environment)"
    # `agentfleet use native` removes the gateway keys on purpose; an update
    # (including the automatic one) then keeps the Claude login.
    if previous.get("gatewayKeysOwned") and not switched_to_native:
        fail("previously bundle-owned gateway settings are incomplete; provide --gateway-url and --gateway-token-env")
    return False, "direct Anthropic (no gateway)"


def prompt(text: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        answer = input(f"{text}{suffix}: ").strip()
    except EOFError:
        fail("setup input ended before the wizard finished; rerun it in a terminal or pass --provider")
    return answer or default


