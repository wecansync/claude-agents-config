def reconcile_module():
    """Load the bundle's fleet-reconcile.py (a hyphenated script) once."""
    global _RECONCILE_MODULE
    if _RECONCILE_MODULE is None:
        spec = importlib.util.spec_from_file_location("agentfleet_fleet_reconcile", SCRIPTS_ROOT / "fleet-reconcile.py")
        if spec is None or spec.loader is None:
            fail("bundle is missing scripts/fleet-reconcile.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _RECONCILE_MODULE = module
    return _RECONCILE_MODULE


