def agent_for_profile(
    source: bytes,
    model: str,
    fleet_hash: str,
    old_models: set[str],
    fallbacks: object = None,
    agent_brain: bool = False,
) -> bytes:
    """Specialise a bundle agent template exactly as claude-fleet-sync would
    render it, so a later ``claude-fleet-sync --check`` finds no drift."""
    text = source.decode("utf-8")
    # Keep the generated lane name stable; only frontmatter model-bearing fields
    # and source hash vary between gateway and direct-Anthropic profiles. The
    # generator always ends a description with "Runs on <model>.", so only
    # that clause is rewritten -- never a model-like word elsewhere in it.
    text = re.sub(
        r'^(description: .*Runs on ).*\.("?)\n',
        lambda match: f"{match.group(1)}{model}.{match.group(2)}\n",
        text, count=1, flags=re.MULTILINE,
    )
    # The generator's other wording, for lanes without their own text:
    # "Alternate <role> lane on <model>. Use when ...".
    text = re.sub(
        r'^(description: "Alternate [a-z-]+ lane on ).+?(\. Use when )',
        lambda match: f"{match.group(1)}{model}{match.group(2)}",
        text, count=1, flags=re.MULTILINE,
    )
    text = re.sub(r"^model: .*\n", f"model: {json.dumps(model)}\n", text, count=1, flags=re.MULTILINE)
    fallback_values = [value for value in fallbacks if isinstance(value, str) and value][:3] if isinstance(fallbacks, list) else []
    fallback_line = f"fallbackModel: {json.dumps(','.join(fallback_values))}\n" if fallback_values else ""
    if re.search(r"^fallbackModel: .*\n", text, flags=re.MULTILINE):
        if fallback_line:
            text = re.sub(r"^fallbackModel: .*\n", fallback_line, text, count=1, flags=re.MULTILINE)
        else:
            text = re.sub(r"^fallbackModel: .*\n", "", text, count=1, flags=re.MULTILINE)
    elif fallback_line:
        text = re.sub(r"^(model: .*\n)", r"\1" + fallback_line, text, count=1, flags=re.MULTILINE)
    has_memory = MEMORY_TOOLS_SUFFIX in text
    if agent_brain and not has_memory:
        text = re.sub(r"^(tools: .*)\n", lambda match: match.group(1) + MEMORY_TOOLS_SUFFIX + "\n", text, count=1, flags=re.MULTILINE)
        text = text.replace(MEMORY_ANCHOR, MEMORY_ANCHOR + MEMORY_LIFECYCLE, 1)
    elif not agent_brain and has_memory:
        text = text.replace(MEMORY_TOOLS_SUFFIX, "", 1).replace(MEMORY_LIFECYCLE, "", 1)
    text = re.sub(r"source-sha256: [0-9a-f]+", f"source-sha256: {fleet_hash}", text, count=1)
    return text.encode("utf-8")


def obsolete_paths(previous: dict, specs: dict, home: Path, bin_dir: Path, config_root: Path) -> list[Path]:
    """Files an earlier install created that this one no longer writes.

    Covers generated agents for retired lanes and managed scripts that were
    renamed. A previously owned file is retired only while it is still
    recognisably ours (marker present or content unchanged since install);
    any generated fleet agent without a lane in the new map goes too, which
    is exactly what claude-fleet-sync would prune.
    """
    found: dict[str, Path] = {}
    owned = {Path(item["path"]): item for item in (metadata_records(previous, home, bin_dir, config_root) if previous else [])}
    for path, item in owned.items():
        if path in specs or path.is_symlink() or not path.is_file():
            continue
        data = path.read_bytes()
        # Generated agents are rewritten by claude-fleet-sync after install,
        # so their bytes rarely match the install record; the generator
        # marker identifies them instead. Other files must still carry the
        # bundle marker or be unchanged since install.
        is_agent = path.parent == home / ".claude" / "agents" and path.name.startswith("fleet-")
        if (is_agent and GENERATED_MARKER.encode() in data) or (not is_agent and MARKER.encode() in data) or bytes_sha256(data) == item.get("sha256"):
            found[str(path)] = path
    agents = home / ".claude" / "agents"
    if agents.is_dir():
        for path in agents.glob("fleet-*.md"):
            if path in specs or path in owned or path.is_symlink() or not path.is_file():
                continue
            # Unowned files are pruned only when they are a lane this bundle
            # shipped before (a regenerated agent from an older release);
            # anything else is the user's and stays.
            lane = path.stem.removeprefix("fleet-")
            if lane in RETIRED_LANES and GENERATED_MARKER.encode() in path.read_bytes():
                found[str(path)] = path
    return [found[key] for key in sorted(found)]


def mode_name(mode: int) -> str:
    exact = stat.S_IMODE(mode)
    if exact == 0o755:
        return "0o755"
    if exact == 0o600:
        return "0o600"
    if exact == 0o644:
        return "0o644"
    return oct(exact)


