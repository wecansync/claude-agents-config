def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def bytes_sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def validate_rel_path(value: object, label: str) -> str:
    if not isinstance(value, str) or not value or "\\" in value:
        fail(f"{label} contains an invalid path: {value!r}")
    path = Path(value)
    if path.is_absolute() or ".." in path.parts or value in {"", "."}:
        fail(f"{label} contains an unsafe path: {value!r}")
    return value


def validate_bundle(bundle: Path) -> tuple[dict, str]:
    """Verify every source byte before any target write occurs."""
    manifest = load_json(bundle / "manifest.json", "bundle manifest")
    if manifest.get("format") != "claude-agents-config.bundle.v1":
        fail("bundle manifest has an invalid format marker")
    version_path = bundle / "VERSION"
    if not version_path.is_file():
        fail(f"missing VERSION: {version_path}")
    version = version_path.read_text(encoding="utf-8").strip()
    if not version or manifest.get("version") != version:
        fail(f"VERSION does not match manifest version ({version!r} vs {manifest.get('version')!r})")
    records = manifest.get("files")
    if not isinstance(records, list) or not records:
        fail("manifest.files is empty or invalid")
    expected: dict[str, dict] = {}
    for item in records:
        if not isinstance(item, dict):
            fail("manifest contains a non-object file record")
        rel = validate_rel_path(item.get("path"), "manifest")
        digest = item.get("sha256")
        mode = item.get("mode")
        if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            fail(f"manifest has an invalid checksum for {rel}")
        if mode not in {"0o644", "0o755"}:
            fail(f"manifest mode for {rel} must be logical 0o644 or 0o755")
        if rel in expected:
            fail(f"manifest lists {rel} more than once")
        expected[rel] = item
        path = bundle / rel
        if not path.is_file() or path.is_symlink():
            fail(f"manifest file is missing or not regular: {path}")
        if os.name != "nt":
            # Only the executable bit is part of a file's logical mode: a git
            # checkout under umask 0002 is group-writable, and the checksums
            # below prove the content. World-writable files are refused,
            # because anyone could change them after that check.
            actual_mode = stat.S_IMODE(path.stat().st_mode)
            if actual_mode & 0o002 or not actual_mode & 0o400 or bool(actual_mode & 0o100) != (mode == "0o755"):
                fail(f"mode mismatch before installation: {path} is {oct(actual_mode)}, expected {mode}")
        actual = file_sha256(path)
        if actual != digest:
            fail(f"checksum mismatch before installation: {path}")

    checksum_path = bundle / "checksums.sha256"
    if not checksum_path.is_file():
        fail(f"missing checksums.sha256: {checksum_path}")
    listed: dict[str, str] = {}
    for line_number, line in enumerate(checksum_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        match = re.fullmatch(r"([0-9a-f]{64})  (.+)", line)
        if not match:
            fail(f"invalid checksums.sha256 line {line_number}")
        digest, rel = match.groups()
        rel = validate_rel_path(rel, "checksums.sha256")
        if rel in listed:
            fail(f"checksums.sha256 lists {rel} more than once")
        listed[rel] = digest
    if listed != {rel: item["sha256"] for rel, item in expected.items()}:
        fail("checksums.sha256 does not have exact parity with manifest.json")

    actual_paths = set()
    for path in bundle.rglob("*"):
        relative_parts = path.relative_to(bundle).parts
        if ".git" in path.parts or (relative_parts and relative_parts[0] in BUNDLE_CONTEXT_DIRS):
            continue
        if path.is_dir():
            if path.name == "__pycache__":
                fail(f"remove generated __pycache__ from bundle: {path}")
            continue
        rel = path.relative_to(bundle).as_posix()
        if rel in {"manifest.json", "checksums.sha256"}:
            continue
        actual_paths.add(rel)
    if actual_paths != set(expected):
        extras = sorted(actual_paths - set(expected))
        missing = sorted(set(expected) - actual_paths)
        details = []
        if extras:
            details.append("unlisted: " + ", ".join(extras))
        if missing:
            details.append("missing: " + ", ".join(missing))
        fail("bundle inventory differs from manifest (" + "; ".join(details) + ")")

    # Scan every packaged text file before any target write. Runtime credential
    # references (environment names and bearer construction) are not secrets;
    # literal secret-shaped values and machine-local paths are forbidden.
    for rel in expected:
        path = bundle / rel
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            fail(f"cannot scan bundle file {path}: {exc}")
        if any(value in text for value in FORBIDDEN_SOURCE_STRINGS):
            fail(f"forbidden machine-local path in bundle: {path}")
        if any(pattern.search(text) for pattern in SOURCE_SECRET_PATTERNS):
            fail(f"credential-shaped literal in bundle: {path}")

    # Parse the structures needed by both profiles while still in preflight.
    template = load_json(bundle / "config/settings.template.json", "settings template")
    template_env = template.get("env") if isinstance(template.get("env"), dict) else {}
    if template.get("autoCompactWindow") != AUTO_COMPACT_WINDOW or template_env.get("CLAUDE_CODE_AUTO_COMPACT_WINDOW") != AUTO_COMPACT_ENV:
        fail(f"settings template must compact at {AUTO_COMPACT_WINDOW} tokens")
    fleet = load_json(bundle / "config/delegate-fleet.json", "fleet configuration")
    if fleet.get("version") != "delegate-fleet.v1" or not isinstance(fleet.get("lanes"), dict):
        fail("config/delegate-fleet.json is not a delegate-fleet.v1 map")
    if not fleet["lanes"]:
        fail("bundle fleet must contain at least one lane")
    for rel in (PROVIDER_POLICY_PATH, PROVIDER_CATALOG_MODULE, RECONCILE_SCRIPT):
        if not (bundle / rel).is_file():
            fail(f"bundle is incomplete; missing provider reconciliation file {bundle / rel}")
    policy = load_json(bundle / PROVIDER_POLICY_PATH, "provider policy")
    if policy.get("version") != "provider-policy.v1" or not isinstance(policy.get("provider"), str) or not re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,63}", policy["provider"]):
        fail("provider policy has an invalid format or provider")
    if not isinstance(policy.get("families"), list):
        fail("provider policy has no family list")
    return manifest, version


def parse_version(text: str) -> tuple[int, int, int]:
    match = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", text)
    if not match:
        return (0, 0, 0)
    return tuple(int(part or 0) for part in match.groups())  # type: ignore[return-value]


def node_path(require: bool = False) -> Path | None:
    candidate = shutil.which("node")
    if not candidate:
        if require:
            fail("Node.js >=18 is required when model discovery or fleet sync is enabled")
        return None
    path = Path(candidate).resolve(strict=False)
    try:
        result = subprocess.run([str(path), "--version"], text=True, capture_output=True, check=False)
    except OSError:
        result = None
    if result is None or result.returncode != 0 or parse_version(result.stdout) < (18, 0, 0):
        if require:
            fail("Node.js >=18 is required when model discovery or fleet sync is enabled")
        return None
    return path


